CREATE TABLE AP_AUTHORIZATION (
 USER_ID VARCHAR2(128 CHAR) PRIMARY KEY,
 VIEWER NUMBER(1) DEFAULT 0 NOT NULL CHECK (VIEWER IN (0,1)),
 EDITOR NUMBER(1) DEFAULT 0 NOT NULL CHECK (EDITOR IN (0,1)),
 ADMINISTRATOR NUMBER(1) DEFAULT 0 NOT NULL CHECK (ADMINISTRATOR IN (0,1)),
 ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVE IN (0,1))
);
CREATE TABLE AP_SESSION (
 TOKEN_HASH VARCHAR2(64 CHAR) PRIMARY KEY,
 USER_ID VARCHAR2(128 CHAR) NOT NULL REFERENCES AP_AUTHORIZATION (USER_ID),
 CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 LAST_SEEN_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX AP_SESSION_USER ON AP_SESSION (USER_ID);
CREATE TABLE AP_AUTH_AUDIT (
 ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
 USER_ID VARCHAR2(128 CHAR) NOT NULL,
 ACTION VARCHAR2(32 CHAR) NOT NULL,
 ROLES_JSON VARCHAR2(128 CHAR) NOT NULL,
 ACTIVE NUMBER(1) NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE OR REPLACE TRIGGER AP_AUTH_AUDIT_IMMUTABLE
 BEFORE UPDATE OR DELETE ON AP_AUTH_AUDIT
 BEGIN
  RAISE_APPLICATION_ERROR(-20001, 'Authorization audit is append only');
 END;
