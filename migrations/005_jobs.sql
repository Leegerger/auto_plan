-- Durable computation records are separate from immutable shared plan history.
CREATE TABLE AP_JOB_HEAD (
 ID NUMBER(1) PRIMARY KEY CHECK (ID=1),
 NEXT_FIFO NUMBER(20) NOT NULL,
 GENERATION VARCHAR2(36)
);
INSERT INTO AP_JOB_HEAD (ID,NEXT_FIFO) VALUES (1,1);
CREATE TABLE AP_JOB (
 JOB_ID VARCHAR2(36) PRIMARY KEY,
 ACTOR_ID VARCHAR2(128) NOT NULL,
 FIFO_NO NUMBER(20) UNIQUE NOT NULL,
 FROZEN_BLOB BLOB NOT NULL,
 FROZEN_SHA VARCHAR2(64) NOT NULL,
 SOURCE_REVISION NUMBER(20) NOT NULL,
 INPUT_VERSION NUMBER(20) NOT NULL,
 LATEST_ADOPTION NUMBER(20) NOT NULL,
 STATE VARCHAR2(16) NOT NULL CHECK (STATE IN ('queued','running','completed','stopped','interrupted','failed')),
 GENERATION VARCHAR2(36),
 RUN_ID VARCHAR2(36),
 STOP_REQUESTED_AT TIMESTAMP WITH TIME ZONE,
 STOP_REASON VARCHAR2(64),
 PROGRESS_BLOB BLOB,
 RESULT_BLOB BLOB,
 CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 STARTED_AT TIMESTAMP WITH TIME ZONE,
 ENDED_AT TIMESTAMP WITH TIME ZONE
);
CREATE INDEX AP_JOB_QUEUE ON AP_JOB (STATE,FIFO_NO);
CREATE TABLE AP_JOB_KEY (
 SUBMISSION_ID VARCHAR2(36) PRIMARY KEY,
 ACTOR_ID VARCHAR2(128) NOT NULL,
 REQUEST_SHA VARCHAR2(64),
 STATUS VARCHAR2(16) NOT NULL CHECK (STATUS IN ('ACCEPTED','ABORTED_VOID')),
 JOB_ID VARCHAR2(36) UNIQUE REFERENCES AP_JOB(JOB_ID),
 RESULT_BLOB BLOB NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE AP_JOB_CANDIDATE (
 CANDIDATE_ID VARCHAR2(36) PRIMARY KEY,
 JOB_ID VARCHAR2(36) NOT NULL REFERENCES AP_JOB(JOB_ID),
 PAYLOAD_SHA VARCHAR2(64) NOT NULL,
 PAYLOAD_BLOB BLOB,
 OFFERED NUMBER(1) DEFAULT 1 NOT NULL CHECK (OFFERED IN (0,1)),
 PUBLISHED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 LAST_VIEWED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 EXPIRED_AT TIMESTAMP WITH TIME ZONE,
 UNIQUE (JOB_ID,PAYLOAD_SHA)
);
CREATE INDEX AP_JOB_CANDIDATE_EXPIRY ON AP_JOB_CANDIDATE (LAST_VIEWED_AT);
