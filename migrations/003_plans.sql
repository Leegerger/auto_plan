-- Complete input version is the mutex/epoch for facts, locks, reset and inputs.
CREATE TABLE AP_PLAN_HEAD (
 ID NUMBER(1) PRIMARY KEY CHECK (ID=1),
 CURRENT_REVISION NUMBER(19) DEFAULT 0 NOT NULL,
 CURRENT_ADOPTION NUMBER(19) DEFAULT 0 NOT NULL
);
INSERT INTO AP_PLAN_HEAD (ID,CURRENT_REVISION,CURRENT_ADOPTION) VALUES (1,0,0);
CREATE TABLE AP_PLAN_CONTEXT (
 INPUT_VERSION NUMBER(19) PRIMARY KEY REFERENCES AP_INPUT_REVISION(INPUT_VERSION),
 CONTEXT_BLOB BLOB NOT NULL,
 SHA256 VARCHAR2(64 CHAR) NOT NULL,
 ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE AP_PLAN_SNAPSHOT (
 SHA256 VARCHAR2(64 CHAR) PRIMARY KEY,
 SNAPSHOT_BLOB BLOB NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE AP_PLAN_REVISION (
 REVISION_NO NUMBER(19) PRIMARY KEY,
 SNAPSHOT_SHA VARCHAR2(64 CHAR) NOT NULL REFERENCES AP_PLAN_SNAPSHOT(SHA256),
 INPUT_VERSION NUMBER(19) NOT NULL REFERENCES AP_INPUT_REVISION(INPUT_VERSION),
 ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
 OPERATION_KIND VARCHAR2(16 CHAR) NOT NULL,
 PENDING NUMBER(1) NOT NULL CHECK (PENDING IN (0,1)),
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE AP_PLAN_EFFECT (
 REVISION_NO NUMBER(19) NOT NULL REFERENCES AP_PLAN_REVISION(REVISION_NO),
 EFFECT_SHA VARCHAR2(64 CHAR) NOT NULL,
 EFFECT_JSON VARCHAR2(2000 CHAR) NOT NULL,
 PRIMARY KEY (REVISION_NO,EFFECT_SHA)
);
CREATE TABLE AP_PLAN_ADOPTION (
 ADOPTION_NO NUMBER(19) PRIMARY KEY,
 REVISION_NO NUMBER(19) NOT NULL REFERENCES AP_PLAN_REVISION(REVISION_NO),
 SNAPSHOT_SHA VARCHAR2(64 CHAR) NOT NULL REFERENCES AP_PLAN_SNAPSHOT(SHA256),
 ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE AP_ADOPTED_CELL (
 ADOPTION_NO NUMBER(19) NOT NULL REFERENCES AP_PLAN_ADOPTION(ADOPTION_NO),
 CELL_SHA VARCHAR2(64 CHAR) NOT NULL,
 PRODUCTION_DATE DATE NOT NULL,
 LINE_CODE VARCHAR2(64 CHAR) NOT NULL,
 MODEL_CODE VARCHAR2(64 CHAR) NOT NULL,
 QUANTITY NUMBER(19) NOT NULL,
 PRIMARY KEY(ADOPTION_NO,CELL_SHA)
);
CREATE TABLE AP_PLAN_KEY (
 OPERATION_ID VARCHAR2(36 CHAR) PRIMARY KEY,
 ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
 OPERATION_KIND VARCHAR2(16 CHAR) NOT NULL,
 STATUS VARCHAR2(20 CHAR) NOT NULL CHECK (STATUS IN ('COMMITTED','ABORTED_VOID')),
 REQUEST_SHA VARCHAR2(64 CHAR),
 RESULT_BLOB BLOB NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE AP_PLAN_AUDIT (
 REVISION_NO NUMBER(19) PRIMARY KEY REFERENCES AP_PLAN_REVISION(REVISION_NO),
 ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
 OPERATION_KIND VARCHAR2(16 CHAR) NOT NULL,
 OPERATION_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES AP_PLAN_KEY(OPERATION_ID),
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE OR REPLACE TRIGGER AP_PLAN_CONTEXT_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_PLAN_CONTEXT
BEGIN RAISE_APPLICATION_ERROR(-20029,'Plan context is immutable'); END;
/
CREATE OR REPLACE TRIGGER AP_PLAN_SNAPSHOT_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_PLAN_SNAPSHOT
BEGIN RAISE_APPLICATION_ERROR(-20029,'Plan snapshot is immutable'); END;
/
CREATE OR REPLACE TRIGGER AP_PLAN_REVISION_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_PLAN_REVISION
BEGIN RAISE_APPLICATION_ERROR(-20029,'Plan revision is immutable'); END;
/
CREATE OR REPLACE TRIGGER AP_PLAN_EFFECT_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_PLAN_EFFECT
BEGIN RAISE_APPLICATION_ERROR(-20029,'Plan effects are immutable'); END;
/
CREATE OR REPLACE TRIGGER AP_PLAN_ADOPTION_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_PLAN_ADOPTION
BEGIN RAISE_APPLICATION_ERROR(-20029,'Adopted plan is immutable'); END;
/
CREATE OR REPLACE TRIGGER AP_ADOPTED_CELL_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_ADOPTED_CELL
BEGIN RAISE_APPLICATION_ERROR(-20029,'Adopted cells are immutable'); END;
/
CREATE OR REPLACE TRIGGER AP_PLAN_AUDIT_IMMUTABLE BEFORE UPDATE OR DELETE ON AP_PLAN_AUDIT
BEGIN RAISE_APPLICATION_ERROR(-20029,'Plan audit is immutable'); END;
/
COMMIT;
