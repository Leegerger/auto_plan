-- Operator installs explicitly; startup only reads this ledger.
CREATE TABLE AP_SCHEMA_MIGRATION (
 VERSION_NO NUMBER(4) PRIMARY KEY,
 FILENAME VARCHAR2(128) NOT NULL,
 SHA256 VARCHAR2(64) NOT NULL,
 STATUS VARCHAR2(16) NOT NULL CHECK (STATUS IN ('APPLYING','APPLIED','FAILED','BASELINED')),
 COMPLETED_STATEMENTS NUMBER(8) DEFAULT 0 NOT NULL,
 RECOVERY_POINT VARCHAR2(256) NOT NULL,
 OPERATOR_ID VARCHAR2(128) NOT NULL,
 RELEASE_ID VARCHAR2(128) NOT NULL,
 SOURCE_REVISION VARCHAR2(64) NOT NULL,
 STARTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 COMPLETED_AT TIMESTAMP WITH TIME ZONE,
 ERROR_CODE VARCHAR2(32)
);
CREATE TABLE AP_SCHEMA_EVENT (
 EVENT_ID VARCHAR2(36) PRIMARY KEY,
 ACTION VARCHAR2(32) NOT NULL,
 THROUGH_VERSION NUMBER(4),
 RECOVERY_POINT VARCHAR2(256) NOT NULL,
 OPERATOR_ID VARCHAR2(128) NOT NULL,
 RELEASE_ID VARCHAR2(128) NOT NULL,
 SOURCE_REVISION VARCHAR2(64) NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
