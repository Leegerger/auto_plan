CREATE TABLE AP_DEMAND_FILE (
 FILE_ID VARCHAR2(36) PRIMARY KEY,
 ATTRIBUTION_DATE DATE NOT NULL,
 FILE_VERSION NUMBER(18) NOT NULL,
 INPUT_VERSION NUMBER(18) NOT NULL REFERENCES AP_INPUT_REVISION(INPUT_VERSION),
 DOCUMENT_BLOB BLOB NOT NULL,
 SHA256 VARCHAR2(64) NOT NULL,
 ACTOR_ID VARCHAR2(128) NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(ATTRIBUTION_DATE,FILE_VERSION)
);
CREATE TABLE AP_DEMAND_KEY (
 OPERATION_ID VARCHAR2(36) PRIMARY KEY,
 ACTOR_ID VARCHAR2(128) NOT NULL,
 REQUEST_SHA VARCHAR2(64),
 STATUS VARCHAR2(20) NOT NULL CHECK(STATUS IN ('COMMITTED','ABORTED_VOID')),
 RESULT_BLOB BLOB NOT NULL,
 RECORDED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE OR REPLACE TRIGGER AP_DEMAND_FILE_IMMUTABLE
BEFORE UPDATE OR DELETE ON AP_DEMAND_FILE
BEGIN
 RAISE_APPLICATION_ERROR(-20001, 'Demand file history is immutable');
END;
