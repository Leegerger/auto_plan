test('matrix keeps dates and line labels visible while scrolling and closing the panel restores focus', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_WORKSPACE_FIXTURE !== '1', 'Requires representative workspace fixture')
  await page.setViewportSize({ width: 1280, height: 800 })
  await enter(page)
  const trigger = page.getByRole('button', { name: '2026-10-15 L 日内详情', exact: true })
  await trigger.click()
  await page.getByRole('button', { name: '关闭对象面板', exact: true }).click()
  await expect(trigger).toBeFocused()
  const scroll = page.getByRole('region', { name: '周矩阵滚动区域' })
  await scroll.evaluate(element => { element.scrollLeft = 500; element.scrollTop = 300 })
  const remembered=await scroll.evaluate(element=>({left:element.scrollLeft,top:element.scrollTop}))
  const date = await page.getByRole('columnheader', { name: '2026-10-12', exact: true }).boundingBox()
  const line = await page.getByRole('rowheader', { name: 'L 线体 1', exact: true }).boundingBox()
  const container = await scroll.boundingBox()
  expect(date!.y).toBeGreaterThanOrEqual(container!.y)
  expect(date!.y).toBeLessThan(container!.y + 8)
  expect(line!.x).toBeGreaterThanOrEqual(container!.x)
  expect(line!.x).toBeLessThan(container!.x + 8)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('navigation',{name:'主要导航'}).getByRole('link',{name:'需求与资料',exact:true}).click()
  await page.getByRole('navigation',{name:'主要导航'}).getByRole('link',{name:'排程',exact:true}).click()
  await expect(page.getByRole('complementary',{name:'排程对象详情'})).toBeHidden()
  expect(await scroll.evaluate(element=>element.scrollLeft)).toBe(remembered.left)
  expect(await scroll.evaluate(element=>element.scrollTop)).toBe(remembered.top)
})
