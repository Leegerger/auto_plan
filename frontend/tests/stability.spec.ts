import { test, expect } from '@playwright/test'
test('batch aggregate/zero locks, explicit unlock and preferences share the one action queue',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires explicit frozen shared-plan fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'共享计划',exact:true}).click()
  const panel=page.getByRole('region',{name:'数量锁定与稳定性'})
  await expect(panel).toBeVisible()
  await page.getByLabel('锁定生产日',{exact:true}).selectOption('2026-10-15')
  await expect(page.getByLabel('锁定线体',{exact:true}).locator('option[value="L"]')).toBeAttached()
  await page.getByLabel('锁定线体',{exact:true}).selectOption('L')
  await page.getByLabel('锁定机种',{exact:true}).selectOption('M')
  await page.getByRole('button',{name:'加入锁定批次',exact:true}).click()
  await page.getByLabel('锁定生产日',{exact:true}).selectOption('2026-10-16')
  await page.getByRole('button',{name:'加入锁定批次',exact:true}).click()
  await expect(page.getByRole('list',{name:'待锁定批次'})).toContainText('200片')
  await expect(page.getByRole('list',{name:'待锁定批次'})).toContainText('0片 锁零')
  await page.getByRole('button',{name:'批量锁定所选数量',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await expect(page.getByRole('table',{name:'当前数量锁'})).toContainText('锁零')
  const before=await(await page.request.get('/planning/api/plans/current')).json()
  expect(before.context.locks).toEqual([])
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const after=await(await page.request.get('/planning/api/plans/current')).json()
  expect(after.input_version).toBe(before.input_version+1)
  expect(after.context.locks).toHaveLength(2)
  await page.getByRole('button',{name:'批量解锁全部当前锁',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'本机完整动作队列'})).toContainText('显式解锁')
  await page.getByLabel('近期截至周',{exact:true}).fill('15')
  await page.getByLabel('近期容忍度',{exact:true}).fill('12.50')
  await page.getByLabel('近期变动权重',{exact:true}).fill('4')
  await page.getByRole('button',{name:'预览偏好变更',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'本机完整动作队列'})).toContainText('稳定性偏好')
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const final=await(await page.request.get('/planning/api/plans/current')).json()
  expect(final.context.locks).toEqual([])
  expect(final.context.preferences.near_weeks).toBe(15)
  expect(final.context.preferences.near_tolerance_percent).toBe('25/2')
  expect(final.input_version).toBe(after.input_version+1)
  await expect(page.getByLabel('近期容忍度',{exact:true})).toHaveValue('12.5')
  await expect(page.getByRole('table',{name:'逐周稳定性'})).toContainText('12.5%')
  await expect(page.getByRole('table',{name:'逐周稳定性'})).toContainText('新排计划')
  await page.screenshot({path:'/tmp/auto-plan-spec-23/stability-ui.png',fullPage:true})
})
