test('high-risk plan changes require the complete preview and a second confirmation',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires frozen shared-plan fixture')
  await login(page)
  const head=await(await page.request.get('/planning/api/plans/current')).json()
  const headers={Origin:`https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT??'8774'}`,'X-Auto-Plan-Request':'1'}
  const seeded=await page.request.post('/planning/api/plans/save',{headers,data:{base_revision:head.revision,input_version:head.input_version,latest_adoption:head.latest_adoption,operation_id:crypto.randomUUID(),pending:true,operations:[{kind:'replace_plan',plan:{segments:[{id:'risk-a',date:'2026-10-15',line_code:'L',model_code:'M',quantity:200,hours:'5',order:0},{id:'risk-b',date:'2026-10-15',line_code:'L',model_code:'N',quantity:100,hours:'2',order:1}]}}]}})
  expect(seeded.ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByRole('heading',{name:'工作台',exact:true})).toBeVisible()
  await page.getByRole('navigation',{name:'主要导航'}).getByRole('link',{name:'排程',exact:true}).click()
  await page.getByRole('button',{name:'2026-10-15 L 日内详情',exact:true}).click()
  await page.getByLabel('选择生产段 risk-a',{exact:true}).check()
  await page.getByLabel('选择生产段 risk-b',{exact:true}).check()
  await page.getByLabel('手动操作',{exact:true}).selectOption('clear_segments')
  await page.getByRole('button',{name:'加入完整动作并预览',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  const primary=page.getByRole('navigation',{name:'主要导航'})
  await primary.getByRole('link',{name:'需求与资料',exact:true}).click()
  await expect(page.getByRole('button',{name:'共享保存',exact:true})).toHaveCount(0)
  await primary.getByRole('link',{name:'排程',exact:true}).click()
  await expect(page.getByRole('button',{name:'共享保存',exact:true})).toBeVisible()
  let saveRequests=0
  page.on('request',request=>{if(request.method()==='POST'&&request.url().endsWith('/api/plans/save'))saveRequests++})
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  const confirmation=page.getByRole('dialog',{name:'确认高风险变更'})
  await expect(confirmation).toContainText('清空生产段')
  await confirmation.getByRole('button',{name:'返回核对',exact:true}).click()
  await expect(confirmation).toBeHidden()
  expect(saveRequests).toBe(0)
})

