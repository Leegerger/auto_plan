import { test, expect } from '@playwright/test'

test('late alternative is explicit and keeps its selected dates', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_DEMAND_TRIAL_FIXTURE !== '1', 'Requires demand trial fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name: '展开待处理需求', exact: true }).click()
  await page.getByRole('button', { name: '选择需求 M 2026-10-12', exact: true }).click()
  await page.getByRole('button', { name: '按需补排', exact: true }).click()
  await page.getByLabel('补排投入起日', { exact: true }).fill('2026-10-18')
  await page.getByLabel('补排投入终日', { exact: true }).fill('2026-10-19')
  await page.getByLabel('补排调整范围起日', { exact: true }).fill('2026-10-18')
  await page.getByLabel('补排调整范围终日', { exact: true }).fill('2026-10-19')
  await page.getByLabel('补排线体', { exact: true }).selectOption('L')
  await page.getByRole('button', { name: '试算按时覆盖', exact: true }).click()
  const result = page.getByRole('region', { name: '单线补排试算结果', exact: true })
  await expect(result).toContainText('剩余补排目标 400 片合格产出')
  await page.getByRole('button', { name: '查看迟交方案', exact: true }).click()
  await expect(result).toContainText('迟交产出已安排 400 片合格产出')
  await expect(result).toContainText('有效迟交补足 0 片合格产出')
  await expect(result).toContainText('当前未补足缺口 400 片合格产出')
  await expect(page.getByLabel('补排投入起日', { exact: true })).toHaveValue('2026-10-18')
  await expect(page.getByLabel('补排投入终日', { exact: true })).toHaveValue('2026-10-19')

  await result.getByRole('link', { name: '核对确认资料', exact: true }).click()
  await expect(page.getByRole('region', { name: '需求资料定位', exact: true })).toContainText('M · 需求周 2026-10-12 · 出货确认')
  await page.getByRole('button', { name: '新增一行', exact: true }).click()
  const row = page.getByRole('table', { name: '跨周确认批次与禁令', exact: true }).locator('tbody tr').last()
  await expect(row.getByLabel(/机种编码/)).toHaveValue('M')
  await expect(row.getByLabel(/需求周周一/)).toHaveValue('2026-10-12')
  await expect(row.getByLabel(/确认类型/)).toHaveValue('shipping')
  await row.getByLabel(/批次编号/).fill('LATE')
  await row.getByLabel(/确认状态/).selectOption('allowed')
  await row.getByLabel(/生产日期/).fill('2026-10-19')
  await row.getByLabel(/额度/).fill('200')
  await page.getByRole('button', { name: '预览表格变更', exact: true }).click()
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认提交整批', exact: true }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await page.getByRole('link', { name: '返回计划工作区', exact: true }).click()
  const panel = page.getByRole('region', { name: '按需补排试算', exact: true })
  await expect(panel).toContainText('显式迟交方案')
  await expect(result).toHaveCount(0)
  await expect(page.getByLabel('补排投入起日', { exact: true })).toHaveValue('2026-10-18')
  await expect(page.getByLabel('补排线体', { exact: true })).toHaveValue('L')
  await page.getByRole('button', { name: '查看迟交方案', exact: true }).click()
  await expect(result).toContainText('有效迟交补足 200 片合格产出')
  await expect(result).toContainText('当前未补足缺口 200 片合格产出')
  await page.getByRole('button', { name: '选用完整安排并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: /本机临时稿/ }).click()
  const actions = page.getByRole('tabpanel', { name: '本机动作', exact: true })
  await expect(actions).toContainText('显式迟交')
  if (!await actions.getByRole('checkbox', { name: '保存为待处理草稿', exact: true }).isChecked()) await actions.getByText('保存为待处理草稿', { exact: true }).click()
  await expect(actions.getByRole('checkbox', { name: '保存为待处理草稿', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved = await (await page.request.get('/planning/api/plans/current')).json()
  expect(saved.latest_adoption).toBe(0)
  expect(saved.plan.segments.map((r:{date:string;quantity:number})=>[r.date,r.quantity])).toEqual([['2026-10-18',600],['2026-10-19',400]])
  const selection = page.getByRole('region', { name: '所选需求摘要', exact: true })
  await selection.getByRole('link', { name: '补出货确认', exact: true }).click()
  await page.getByLabel('额度 (片) 第1行', { exact: true }).fill('400')
  await page.getByRole('button', { name: '预览表格变更', exact: true }).click()
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认提交整批', exact: true }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await page.getByRole('link', { name: '返回计划工作区', exact: true }).click()
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toHaveCount(0)
  const repreview = page.getByRole('button', { name: '按最新资料重新预览', exact: true })
  if (await repreview.isVisible()) await repreview.click()
  else await page.getByRole('button', { name: '预览当前计划', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await page.getByRole('region', { name: '计划状态', exact: true }).getByRole('button', { name: '正式采用', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: '确认正式采用', exact: true })
  await expect(confirmation).toBeVisible()
  await confirmation.getByRole('button', { name: '正式采用', exact: true }).click()
  await expect(page.getByText(/已正式采用/)).toBeVisible()
  const adopted = await (await page.request.get('/planning/api/plans/current')).json()
  expect(adopted.plan).toEqual(saved.plan)
  const goal = Object.values(adopted.lineage.demand_goals)[0] as {remaining_output_target:number;late:number;on_time:number}
  expect(goal).toMatchObject({remaining_output_target:0,late:400,on_time:600})
})
