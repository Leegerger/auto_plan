import { test, expect } from '@playwright/test'

test('single-line on-time trial keeps qualified target separate and saves only after acceptance', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_DEMAND_TRIAL_FIXTURE !== '1', 'Requires partial demand-trial fixture')
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name: '展开待处理需求', exact: true }).click()
  await page.getByRole('button', { name: '选择需求 M 2026-10-12', exact: true }).click()
  await expect(page.getByRole('button', { name: '按需补排', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '按需补排', exact: true }).click()
  const trial = page.getByRole('region', { name: '按需补排试算', exact: true })
  const result = page.getByRole('region', { name: '单线补排试算结果', exact: true })
  await expect(trial).toContainText('M · 需求周 2026-10-12')
  await expect(page.getByLabel('补排合格产出目标', { exact: true })).toHaveValue('1000')
  await page.getByLabel('补排投入起日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排投入终日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排线体', { exact: true }).selectOption('L')
  const before = await (await page.request.get('/planning/api/plans/current')).json()
  await page.getByRole('button', { name: '试算按时覆盖', exact: true }).click()
  await expect(result).toContainText('仅安排部分按时覆盖')
  await expect(result).toContainText('建议投入 600 片投入')
  await expect(result).toContainText('按时产出已安排 600 片合格产出')
  await expect(result).toContainText('有效按时覆盖 600 片合格产出')
  await expect(result).toContainText('剩余补排目标 400 片合格产出')
  await expect(result.getByRole('table', { name: '建议逐日投入', exact: true }).locator('tbody tr')).toHaveCount(1)
  await expect(result.getByRole('table', { name: '建议逐日投入', exact: true })).toContainText('2026-10-15')
  expect(await (await page.request.get('/planning/api/plans/current')).json()).toEqual(before)
  await page.getByRole('button', { name: /本机临时稿/ }).click()
  await expect(page.getByRole('region', { name: '本机完整动作队列', exact: true }).getByRole('checkbox')).toHaveCount(0)
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await page.getByLabel('补排合格产出目标', { exact: true }).fill('900')
  await expect(result).toHaveCount(0)
  await expect(trial).toContainText('试算已失效')
  await expect(page.getByLabel('补排线体', { exact: true })).toHaveValue('L')
  await page.getByLabel('补排合格产出目标', { exact: true }).fill('1000')
  await page.getByRole('button', { name: '试算按时覆盖', exact: true }).click()
  await expect(result).toContainText('剩余补排目标 400 片合格产出')
  const inputs = await (await page.request.get('/planning/api/inputs')).json()
  const maintained = await page.request.post('/planning/api/inputs/apply', { headers: {
    Origin: `https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT ?? '8774'}`, 'X-Auto-Plan-Request': '1',
  }, data: { base_version: inputs.input_version, changes: { models: inputs.masters.models.map((row: { code: string }) => row.code==='M' ? { ...row, name: '复核后的机种名称' } : row) } } })
  expect(maintained.ok(), await maintained.text()).toBe(true)
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '需求与资料', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await expect(result).toHaveCount(0)
  await expect(page.getByLabel('补排合格产出目标', { exact: true })).toHaveValue('1000')
  await expect(page.getByLabel('补排投入起日', { exact: true })).toHaveValue('2026-10-15')
  await page.getByRole('button', { name: '试算按时覆盖', exact: true }).click()
  await expect(result).toContainText('剩余补排目标 400 片合格产出')
  await page.getByRole('button', { name: '选用完整安排并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  const goals = page.getByRole('region', { name: '补排目标余额', exact: true })
  await expect(goals).toContainText('剩余补排目标 400 片合格产出')
  expect((await (await page.request.get('/planning/api/plans/current')).json()).revision).toBe(before.revision)
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved = await (await page.request.get('/planning/api/plans/current')).json()
  expect(saved.latest_adoption).toBe(0)
  expect(saved.plan.segments).toHaveLength(1)
  expect(saved.plan.segments[0]).toMatchObject({ date: '2026-10-15', line_code: 'L', model_code: 'M', quantity: 600 })
  expect(saved.unallocated).toEqual([])
  expect(Object.values(saved.lineage.demand_goals)).toEqual([expect.objectContaining({ requested_output: 1000, remaining_output_target: 400 })])
  await page.getByRole('button', { name: '2026-10-15 L 日内详情', exact: true }).click()
  await page.getByLabel(`选择生产段 ${saved.plan.segments[0].id}`, { exact: true }).check()
  await page.getByLabel('改量后总量', { exact: true }).fill('500')
  await page.getByLabel('顺延截止日', { exact: true }).fill('2026-10-15')
  await page.getByRole('button', { name: '预览完整改量顺延', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(goals).toContainText('剩余补排目标 500 片合格产出')
  await page.getByRole('button', { name: /本机临时稿/ }).click()
  const action = page.getByRole('region', { name: '本机完整动作队列', exact: true }).getByRole('checkbox').first()
  await action.uncheck()
  await expect(goals).toContainText('剩余补排目标 待重新预览')
  await expect(goals).not.toContainText('400 片合格产出')
  await action.check()
  await page.getByRole('button', { name: '预览本机修改', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(goals).toContainText('剩余补排目标 500 片合格产出')
  await page.getByRole('button', { name: /本机临时稿/ }).click()
  await page.getByRole('button', { name: '撤销最后完整动作', exact: true }).click()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(goals).toContainText('剩余补排目标 400 片合格产出')
  await page.reload()
  await page.getByRole('button', { name: '补排目标 1', exact: true }).click()
  await expect(goals).toContainText('剩余补排目标 400 片合格产出')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_VIEWER')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  if (!await goals.isVisible()) await page.getByRole('button', { name: '补排目标 1', exact: true }).click()
  await expect(goals).toContainText('剩余补排目标 400 片合格产出')
  await expect(page.getByRole('button', { name: '按需补排', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '试算按时覆盖', exact: true })).toHaveCount(0)
})

test('zero-capacity trial retains only an explicit qualified-output goal without production', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_DEMAND_TRIAL_FIXTURE !== '1', 'Requires partial demand-trial fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name: '展开待处理需求', exact: true }).click()
  await page.getByRole('button', { name: '选择需求 N 2026-10-12', exact: true }).click()
  await page.getByRole('button', { name: '按需补排', exact: true }).click()
  await page.getByLabel('补排投入起日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排投入终日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排线体', { exact: true }).selectOption('B')
  const before = await (await page.request.get('/planning/api/plans/current')).json()
  await page.getByRole('button', { name: '试算按时覆盖', exact: true }).click()
  const result = page.getByRole('region', { name: '单线补排试算结果', exact: true })
  await expect(result).toContainText('暂不可安排')
  await expect(result).toContainText('建议投入 0 片投入')
  await expect(result).toContainText('剩余补排目标 1000 片合格产出')
  await expect(page.getByRole('button', { name: '选用完整安排并预览', exact: true })).toHaveCount(0)
  expect(await (await page.request.get('/planning/api/plans/current')).json()).toEqual(before)
  await page.getByRole('button', { name: '仅保留补排目标并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '补排目标余额', exact: true })).toContainText('剩余补排目标 1000 片合格产出')
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved = await (await page.request.get('/planning/api/plans/current')).json()
  expect(saved.plan).toEqual(before.plan)
  expect(saved.latest_adoption).toBe(before.latest_adoption)
  expect(Object.values(saved.lineage.demand_goals)).toContainEqual(expect.objectContaining({ model_code: 'N', requested_output: 1000, remaining_output_target: 1000 }))
})
