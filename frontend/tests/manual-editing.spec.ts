import {test,expect} from '@playwright/test'
const headers={Origin:`https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT ?? '8774'}`,'X-Auto-Plan-Request':'1'}
test('weekly navigation, day details, complete swap, undo, split and shared save',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires frozen shared-plan fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  const base=await(await page.request.get('/planning/api/plans/current')).json()
  const seeded=await page.request.post('/planning/api/plans/save',{headers,data:{base_revision:base.revision,input_version:base.input_version,latest_adoption:base.latest_adoption,operation_id:crypto.randomUUID(),pending:true,operations:[{kind:'replace_plan',plan:{segments:[{id:'manual-a',date:'2026-10-15',line_code:'L',model_code:'M',quantity:600,hours:'15',order:0},{id:'manual-b',date:'2026-10-15',line_code:'L',model_code:'N',quantity:300,hours:'8',order:1}]}}]}})
  expect(seeded.ok()).toBeTruthy()
  await page.getByRole('link',{name:'排程',exact:true}).click()
  await expect(page.getByLabel('计划周次')).toBeVisible()
  await expect(page.getByLabel('计划周次').locator('option')).toHaveCount(15)
  await page.getByLabel('计划周次').selectOption('15')
  await expect(page.getByRole('table',{name:'十五周日期线体计划'})).toContainText('2027-01-24')
  await expect(page.locator('.page-subtitle')).toContainText('第 15 周')
  await expect(page.getByRole('heading',{name:'2026-10-12 · L 日内详情',exact:true})).toBeVisible()
  await page.getByLabel('计划周次').selectOption('1')
  await page.getByRole('button',{name:'2026-10-15 L 日内详情',exact:true}).click()
  await page.getByLabel('选择生产段 manual-a',{exact:true}).check()
  await page.getByLabel('选择生产段 manual-b',{exact:true}).check()
  await page.getByLabel('手动操作',{exact:true}).selectOption('swap_segments')
  await page.getByRole('button',{name:'加入完整动作并预览',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  const details=page.getByRole('table',{name:'日内生产顺序'})
  await expect(details.locator('tbody tr').first()).toContainText('N')
  await expect(details.locator('tbody tr').first()).toContainText('300片')
  await page.getByRole('button',{name:'查看预览',exact:true}).click()
  await expect(page.getByRole('table',{name:'本次完整计划变更'})).toContainText('顺序')
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  await page.getByRole('button',{name:/本机临时稿/}).click()
  const action=page.getByRole('region',{name:'本机完整动作队列'}).getByRole('checkbox').first()
  await action.uncheck()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await expect(details.locator('tbody tr').first()).toContainText('M')
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  await page.getByRole('button',{name:/本机临时稿/}).click()
  await action.check()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await expect(details.locator('tbody tr').first()).toContainText('N')
  const unchanged=await(await page.request.get('/planning/api/plans/current')).json()
  expect(unchanged.plan.segments[0].model_code).toBe('M')
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  await page.getByRole('button',{name:/本机临时稿/}).click()
  await page.getByRole('button',{name:'撤销最后完整动作',exact:true}).click()
  await expect(details.locator('tbody tr').first()).toContainText('M')
  await expect(details.locator('tbody tr').first()).toContainText('600片')
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  await page.getByLabel('选择生产段 manual-b',{exact:true}).uncheck()
  await page.getByLabel('手动操作',{exact:true}).selectOption('split_segment')
  await page.getByLabel('操作数量',{exact:true}).fill('200')
  await page.getByLabel('目标起始日',{exact:true}).fill('2026-10-16')
  await page.getByRole('button',{name:'加入完整动作并预览',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await expect(details.locator('tbody tr').first()).toContainText('400片')
  await page.getByRole('button',{name:'2026-10-16 L 日内详情',exact:true}).click()
  await expect(details).toContainText('200片')
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved=await(await page.request.get('/planning/api/plans/current')).json()
  expect(saved.plan.segments).toHaveLength(3)
  expect(saved.plan.segments.filter((row:{model_code:string})=>row.model_code==='M').map((row:{quantity:number})=>row.quantity)).toEqual([400,200])
  await page.screenshot({path:'/tmp/auto-plan-spec-23/manual-editing-ui.png',fullPage:true})
})
