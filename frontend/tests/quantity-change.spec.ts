import {test, expect} from '@playwright/test'

test('quantity change previews and undoes one whole chain before sharing', async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires frozen shared-plan fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  const base=await(await page.request.get('/planning/api/plans/current')).json()
  const headers={Origin:`https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT ?? '8774'}`,'X-Auto-Plan-Request':'1'}
  const seeded=await page.request.post('/planning/api/plans/save',{headers,data:{base_revision:base.revision,input_version:base.input_version,latest_adoption:base.latest_adoption,operation_id:crypto.randomUUID(),pending:true,operations:[{kind:'replace_plan',plan:{segments:[{id:'quantity-a',date:'2026-10-15',line_code:'L',model_code:'M',quantity:600,hours:'15',order:0},{id:'quantity-b',date:'2026-10-15',line_code:'L',model_code:'N',quantity:400,hours:'9',order:1}]}}]}})
  expect(seeded.ok()).toBeTruthy()
  await page.getByRole('link',{name:'共享计划',exact:true}).click()
  await page.getByRole('button',{name:'2026-10-15 L 日内详情',exact:true}).click()
  await page.getByLabel('选择生产段 quantity-a',{exact:true}).check()
  await page.getByLabel('改量后总量',{exact:true}).fill('800')
  await page.getByLabel('顺延截止日',{exact:true}).fill('2026-10-15')
  await page.getByRole('button',{name:'预览完整改量顺延',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await expect(page.getByRole('table',{name:'未分配投入'})).toContainText('200')
  const details=page.getByRole('table',{name:'日内生产顺序'})
  await expect(details).toContainText('800片')
  await expect(page.getByRole('region',{name:'本机完整动作队列'}).getByRole('checkbox')).toHaveCount(1)
  await page.getByRole('button',{name:'撤销最后完整动作',exact:true}).click()
  await expect(details).toContainText('600片')
  await expect(details).toContainText('400片')
  await page.getByLabel('顺延截止日',{exact:true}).fill('2026-10-16')
  await page.getByRole('button',{name:'预览完整改量顺延',exact:true}).click()
  await expect(details).toContainText('800片')
  const action=page.getByRole('region',{name:'本机完整动作队列'}).getByRole('checkbox').first()
  await action.uncheck()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await expect(details).toContainText('600片')
  await action.check()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await expect(details).toContainText('800片')
  await page.getByRole('button',{name:'2026-10-16 L 日内详情',exact:true}).click()
  await expect(details).toContainText('200片')
  await page.getByText('保存为待处理草稿',{exact:true}).click()
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved=await(await page.request.get('/planning/api/plans/current')).json()
  expect(saved.plan.segments.map((r:{date:string;model_code:string;quantity:number})=>[r.date,r.model_code,r.quantity])).toEqual([['2026-10-15','M',800],['2026-10-15','N',200],['2026-10-16','N',200]])
  await page.screenshot({path:'/tmp/auto-plan-spec-23/quantity-change-ui.png',fullPage:true})
})
