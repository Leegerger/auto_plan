import {test, expect} from '@playwright/test'

test('editor revises one confirmation batch and can trace effective coverage and exact source output', async ({page}) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_OUTPUT_FIXTURE !== '1', 'Requires explicit frozen output fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox', {name:'公司账号'}).fill('OUTPUT_EDITOR')
  await page.getByLabel('公司密码', {exact:true}).fill('company-secret')
  await page.getByRole('button', {name:'登录', exact:true}).click()
  await page.getByRole('link', {name:'需求与资料', exact:true}).click()
  await page.getByRole('link', {name:'基础资料', exact:true}).click()
  await page.getByLabel('资料类别', {exact:true}).selectOption('confirmations')
  await page.getByRole('button', {name:'新增一行',exact:true}).click()
  await page.getByLabel('机种编码 第1行',{exact:true}).selectOption('M')
  await page.getByLabel('需求周周一 第1行',{exact:true}).fill('2026-10-19')
  await page.getByLabel('确认类型 第1行',{exact:true}).selectOption('material')
  await page.getByLabel('批次编号 第1行',{exact:true}).fill('MAT-UI')
  await page.getByLabel('确认状态 第1行',{exact:true}).selectOption('allowed')
  await page.getByLabel('生产日期 第1行',{exact:true}).fill('2026-10-15')
  await page.getByLabel('额度 (片) 第1行',{exact:true}).fill('428')
  await page.getByRole('button', {name:'预览表格变更',exact:true}).click()
  await expect(page.getByText('预览通过，尚未提交',{exact:true})).toBeVisible()
  await page.getByRole('button', {name:'确认提交整批',exact:true}).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  const currentPlan=await(await page.request.get('/planning/api/plans/current')).json()
  const row={id:'output-segment',date:'2026-10-15',line_code:'L',model_code:'M',quantity:1072,hours:'24',order:0}
  const saved=await page.request.post('/planning/api/plans/save',{headers:{Origin:new URL(page.url()).origin,'X-Auto-Plan-Request':'1'},data:{base_revision:currentPlan.revision,input_version:currentPlan.input_version,latest_adoption:currentPlan.latest_adoption,operation_id:crypto.randomUUID(),pending:true,operations:[{kind:'replace_plan',plan:{segments:[row]}}]}})
  expect(saved.ok()).toBeTruthy()
  await page.getByRole('link', {name:'排程',exact:true}).click()
  await page.getByRole('link', {name:'日内工时',exact:true}).click()
  await page.getByLabel('详情生产日期',{exact:true}).fill('2026-10-15')
  await expect(page.getByRole('table',{name:'日内生产顺序'})).toContainText('1072 片')
  await expect(page.getByRole('table',{name:'周需求覆盖'})).toContainText('399')
  await expect(page.getByRole('table',{name:'确认批次使用'})).toContainText('MAT-UI')
  await expect(page.getByRole('table',{name:'产出归属确认明细'})).toContainText('429')
  await page.getByText(/跨线投入.*1072/).click()
  await expect(page.getByRole('table',{name:'产出取整依据'})).toContainText('62377/125')
  await expect(page.getByRole('table',{name:'产出取整依据'})).toContainText('500')
  await page.screenshot({path:'/tmp/auto-plan-spec-23/output-ui.png',fullPage:true})
  await page.getByRole('link',{name:'需求与资料',exact:true}).click()
  await page.getByRole('link',{name:'基础资料',exact:true}).click()
  await page.getByLabel('资料类别',{exact:true}).selectOption('confirmations')
  await expect(page.getByLabel('批次编号 第1行',{exact:true})).toBeDisabled()
  await page.getByLabel('额度 (片) 第1行',{exact:true}).fill('429')
  await page.getByRole('button',{name:'预览表格变更',exact:true}).click()
  await page.getByRole('button',{name:'确认提交整批',exact:true}).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await expect(page.getByRole('table',{name:'跨周确认批次与禁令'}).getByRole('row')).toHaveCount(2)
})
