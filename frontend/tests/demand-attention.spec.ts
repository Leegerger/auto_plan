test('a cross-week ban opens its existing records instead of presenting an ordinary confirmation top-up', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_DEMAND_FIXTURE !== '1', 'Requires the frozen demand fixture')
  await enter(page)
  const inputs = await (await page.request.get('/planning/api/inputs')).json()
  const changed = await page.request.post('/planning/api/inputs/apply', {
    headers: { Origin: new URL(page.url()).origin, 'X-Auto-Plan-Request': '1' },
    data: { base_version: inputs.input_version, changes: { confirmations: [...inputs.business.confirmations.map((row: { batch_id: string }) => row.batch_id === 'SOME' ? { ...row, quantity: 1000 } : row),
      { model_code: 'M', week: '2026-10-19', kind: 'material', batch_id: 'MAT-BAN', status: 'forbidden' }] } },
  })
  expect(changed.ok()).toBeTruthy()
  await page.goto('/planning/schedule')
  await page.getByRole('button', { name: '展开待处理需求', exact: true }).click()
  await page.getByRole('button', { name: '选择需求 M 2026-10-19', exact: true }).click()
  const selection = page.getByRole('region', { name: '所选需求摘要', exact: true })
  await expect(selection.getByRole('link', { name: '补物料确认', exact: true })).toHaveCount(0)
  await selection.getByRole('link', { name: '处理物料禁令', exact: true }).click()
  await expect(page.getByRole('table', { name: '跨周确认批次与禁令', exact: true }).locator('tbody tr')).toHaveCount(2)
  await expect(page.getByLabel('确认状态 第3行', { exact: true })).toHaveValue('forbidden')
  await expect(page.getByLabel('额度 (片) 第1行', { exact: true })).toHaveValue('1000')
})
