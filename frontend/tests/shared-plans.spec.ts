import { test, expect } from '@playwright/test'
const headers = { Origin:'https://localhost:8774', 'X-Auto-Plan-Request':'1' }
test('save, explicit adopt, conflict and unknown-result readonly verification', async ({page}) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE !== '1', 'Requires explicit frozen shared-plan fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'共享计划',exact:true}).click()
  const quantity=page.getByLabel('a投入数量',{exact:true})
  await expect(quantity).toHaveValue('200')
  await quantity.fill('190'); await quantity.blur()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订 2，最近采用版未改变/)).toBeVisible()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await page.getByRole('button',{name:'正式采用',exact:true}).click()
  await expect(page.getByText('已正式采用第 1 版',{exact:true})).toBeVisible()
  await quantity.fill('180'); await quantity.blur()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  const head=await (await page.request.get('/planning/api/plans/current')).json()
  const external=await page.request.post('/planning/api/plans/save',{headers,data:{
    base_revision:head.revision,input_version:head.input_version,latest_adoption:head.latest_adoption,
    operation_id:crypto.randomUUID(),pending:true,operations:[{kind:'patch_plan',segments:[{...head.plan.segments[0],quantity:170}]}],
  }})
  expect(external.ok()).toBeTruthy()
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText('其他用户已修改关联范围，请核对差异',{exact:true})).toBeVisible()
  await expect(quantity).toHaveValue('180')
  await expect(page.getByRole('table',{name:'其他用户的计划变更'})).toContainText('投入数量')
  await expect(page.getByRole('table',{name:'其他用户的计划变更'})).toContainText('170')
  await page.getByRole('button',{name:'按最新资料重新预览',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await page.route('**/api/plans/save',async route=>{ await route.fetch(); await route.abort('failed') },{times:1})
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText('前次保存结果未知，当前只读。请先核实，避免重复保存或采用。',{exact:true})).toBeVisible()
  await expect(quantity).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('button',{name:'核实前次操作',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'核实前次操作',exact:true}).click()
  await expect(page.getByText(/已核实前次操作成功/)).toBeVisible()
  await expect(quantity).toBeEnabled(); await expect(quantity).toHaveValue('180')
  await quantity.fill('177'); await quantity.blur()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await page.route('**/api/plans/save',async route=>{
    await route.fetch()
    await route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({detail:'代理响应失败'})})
  },{times:1})
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(quantity).toBeDisabled()
  await expect(page.getByRole('button',{name:'核实前次操作',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'核实前次操作',exact:true}).click()
  await expect(page.getByText(/已核实前次操作成功/)).toBeVisible()
  await expect(quantity).toHaveValue('177')
  await quantity.fill('175'); await quantity.blur()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  const before=await (await page.request.get('/planning/api/plans/current')).json()
  await page.route('**/api/plans/save',route=>route.abort('failed'),{times:1})
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(quantity).toBeDisabled()
  await page.getByRole('button',{name:'核实前次操作',exact:true}).click()
  await expect(page.getByText(/已核实前次操作作废/)).toBeVisible()
  expect((await (await page.request.get('/planning/api/plans/current')).json()).revision).toBe(before.revision)
  await expect(quantity).toHaveValue('175')
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  expect((await (await page.request.get('/planning/api/plans/current')).json()).revision).toBe(before.revision+1)
  await page.screenshot({path:'/tmp/auto-plan-spec-23/shared-plan-ui.png',fullPage:true})
})
