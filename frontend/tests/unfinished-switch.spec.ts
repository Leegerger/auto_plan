import { test, expect } from '@playwright/test'

test('registers, arranges and saves actual remaining work without granting continuity or target readiness', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_UNFINISHED_SWITCH_FIXTURE !== '1', 'Requires unfinished actual switch fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  const before = await (await page.request.get('/planning/api/plans/current')).json()
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await expect(page.getByLabel('线体状态类别', { exact: true })).toBeVisible()
  await page.getByLabel('线体状态类别', { exact: true }).selectOption('unfinished_switch')
  await page.getByLabel('确认线体 L', { exact: true }).check()
  await page.getByLabel('原切机作业 L', { exact: true }).fill('actual-r-s')
  await page.getByLabel('切机原 Recipe L', { exact: true }).selectOption('R')
  await page.getByLabel('切机目标 Recipe L', { exact: true }).selectOption('S')
  await page.getByLabel('切机实际开始时点 L', { exact: true }).fill('2026-10-11T20:00')
  await page.getByLabel('现场剩余工时 L', { exact: true }).fill('4')
  await page.getByLabel('整次标准工时 L', { exact: true }).fill('12')
  await page.getByLabel('现场已完成工时 L', { exact: true }).fill('8')
  await page.getByLabel('线体状态来源', { exact: true }).fill('跨周交班点检')
  await page.getByRole('button', { name: '关闭对象面板', exact: true }).click()
  await page.getByRole('button', { name: '打开对象面板', exact: true }).click()
  await expect(page.getByLabel('现场剩余工时 L', { exact: true })).toHaveValue('4')
  await expect(page.getByLabel('线体状态来源', { exact: true })).toHaveValue('跨周交班点检')
  await page.getByRole('button', { name: '加入状态确认并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  const records = page.getByRole('table', { name: '现场线体状态记录' })
  await expect(records).toContainText('未完成切机 R → S')
  await expect(records).toContainText('现场剩余 4 小时')
  await expect(records).toContainText('整次标准 12 小时')
  await expect(records).toContainText('现场已完成 8 小时')
  await expect(records).not.toContainText('保留 S')
  await expect(page.getByRole('button', { name: '安排剩余作业 actual-r-s', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '安排剩余作业 actual-r-s', exact: true }).click()
  await page.getByLabel('剩余切机日期 1', { exact: true }).fill('2026-10-20')
  await page.getByRole('button', { name: '加入剩余切机并预览', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '剩余切机安排位于授权调整范围之外' })).toBeVisible()
  await page.getByLabel('剩余切机日期 1', { exact: true }).fill('2026-10-15')
  await page.getByRole('button', { name: '加入剩余切机并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  const day = page.getByRole('button', { name: '2026-10-15 L 日内详情', exact: true })
  await expect(day).toContainText('切机 4.0000 小时')
  const unchanged = await (await page.request.get('/planning/api/plans/current')).json()
  expect(unchanged.revision).toBe(before.revision)
  expect(unchanged.context.line_states.records).toEqual([])
  await day.click()
  await page.getByLabel('追加起日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('追加终日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('追加机种', { exact: true }).selectOption('P')
  await page.getByLabel('追加线体', { exact: true }).selectOption('L')
  await page.getByLabel('操作数量', { exact: true }).fill('100')
  await page.getByRole('button', { name: '加入完整动作并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: '日内生产顺序' })).toContainText('P')
  await expect(day).toContainText('切机 4.0000 小时')
  await page.getByRole('button', { name: '查看预览', exact: true }).click()
  await expect(page.getByRole('region', { name: '正式采用所需现场依据' })).toContainText('连续')
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeDisabled()
  await page.getByRole('tabpanel', { name: '变更预览' }).getByText('保存为待处理草稿', { exact: true }).click()
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved = await (await page.request.get('/planning/api/plans/current')).json()
  expect(saved.pending).toBe(true)
  expect(saved.evaluation.switch_count).toBe(1)
  expect(saved.evaluation.capacity_valid).toBe(true)
  expect(saved.evaluation.executable).toBe(false)
  expect(saved.plan.switches).toHaveLength(1)
  expect(saved.plan.switches[0].id).toBe('actual-r-s')
  expect(saved.plan.switches[0].allocations[0].hours).toBe('4')
  expect(saved.plan.switches[0].residual_record_id).toBe(saved.context.line_states.records[0].id)
  const row = page.getByRole('rowheader', { name: 'L 一线', exact: true })
  await expect(row).toContainText('未完成切机 R → S')
  await expect(row).toContainText('本周新增 0 次 · 跨周承接 1 次')
  await expect(row).not.toContainText('保留 S')
  await page.getByLabel('计划周次', { exact: true }).selectOption('2')
  await expect(row).toContainText('保留 S')
  await expect(row).toContainText('计划推算')
  const current = page.getByRole('region', { name: '当前现场确认', exact: true })
  await expect(current).toContainText('未完成切机 R → S')
  await page.reload()
  await page.getByLabel('计划周次', { exact: true }).selectOption('1')
  await expect(row).toContainText('现场剩余 4 小时')
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await expect(records).toContainText('跨周交班点检')
  await page.getByRole('button', { name: '更正线体 L 状态', exact: true }).click()
  await page.getByLabel('现场剩余工时 L', { exact: true }).fill('2')
  await page.getByLabel('现场已完成工时 L', { exact: true }).fill('')
  await page.getByRole('button', { name: '加入状态确认并预览', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '更正确认状态必须填写原因' })).toBeVisible()
  await page.getByLabel('线体状态更正原因', { exact: true }).fill('点检更正实际剩余量，未记录累计完成量')
  await page.getByRole('button', { name: '加入状态确认并预览', exact: true }).click()
  await expect(records).toContainText('现场剩余 2 小时')
  await expect(records).not.toContainText('现场已完成')
  await page.getByRole('button', { name: '安排剩余作业 actual-r-s', exact: true }).click()
  await page.getByLabel('剩余切机工时 1', { exact: true }).fill('2')
  await page.getByRole('button', { name: '加入剩余切机并预览', exact: true }).click()
  await expect(day).toContainText('切机 2.0000 小时')
  await page.getByRole('button', { name: '查看预览', exact: true }).click()
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeDisabled()
  await page.getByRole('tabpanel', { name: '变更预览' }).getByText('保存为待处理草稿', { exact: true }).click()
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const corrected = await (await page.request.get('/planning/api/plans/current')).json()
  expect(corrected.context.line_states.records[0].unfinished_switch.remaining_hours).toBe('2')
  expect(corrected.context.line_states.records[0].unfinished_switch.completed_hours).toBeUndefined()
  expect(corrected.context.line_states.audit.at(-1).reason).toContain('点检更正')
  const historical = await (await page.request.get(`/planning/api/plans/revisions/${saved.revision}`)).json()
  expect(historical.snapshot.line_states.records[0].unfinished_switch.remaining_hours).toBe('4')
  expect(historical.snapshot.line_states.records[0].unfinished_switch.completed_hours).toBe('8')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_VIEWER')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await expect(records).toContainText('现场剩余 2 小时')
  await expect(page.getByRole('button', { name: '加入状态确认并预览', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '安排剩余作业 actual-r-s', exact: true })).toHaveCount(0)
})
