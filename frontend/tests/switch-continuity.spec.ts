import { test, expect } from '@playwright/test'

test('remaining-job continuity uses a reviewed basis before adoption', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_CONTINUITY_FIXTURE !== '1', 'Requires actual remaining-job fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  const headers = { Origin: `https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT ?? '8774'}`, 'X-Auto-Plan-Request': '1' }
  async function head() { return (await page.request.get('/planning/api/plans/current')).json() }
  async function save(operations: Record<string, unknown>[]) {
    const current = await head()
    const response = await page.request.post('/planning/api/plans/save', { headers, data: {
      base_revision: current.revision, input_version: current.input_version, latest_adoption: current.latest_adoption,
      operation_id: crypto.randomUUID(), pending: true, operations,
    } })
    expect(response.ok(), await response.text()).toBe(true)
  }
  await save([{ kind: 'confirm_line_states', rows: [{ line_code: 'L', effective_at: '2026-10-12T08:00:00+08:00', state: 'unfinished_switch', recipe_code: null,
    source: '跨周实际进度', unfinished_switch: { job_id: 'continuity-r-s', started_at: '2026-10-11T20:00:00+08:00', from_recipe: 'R', to_recipe: 'S', remaining_hours: '4', standard_hours: '12', completed_hours: '8' } }] }])
  const progress = (await head()).context.line_states.records[0]
  await save([{ kind: 'patch_plan', switches: [{ id: 'continuity-r-s', line_code: 'L', from_recipe: 'R', to_recipe: 'S', residual_record_id: progress.id,
    allocations: [{ date: '2026-10-15', order: 0, hours: '4', idle_hours: '0' }] }],
    segments: [{ id: 'after-continuity', date: '2026-10-15', line_code: 'L', model_code: 'P', quantity: 100, order: 1, hours: '3' }] }])
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name: '预览当前计划', exact: true }).click()
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeDisabled()
  await expect(page.getByRole('region', { name: '正式采用所需现场依据' })).toContainText('连续')
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await page.getByRole('button', { name: '安排剩余作业 continuity-r-s', exact: true }).click()
  const detail = page.getByRole('region', { name: '剩余切机连续性', exact: true })
  await expect(detail).toBeVisible()
  await expect(detail).toContainText('尚未确认')
  await expect(detail.getByRole('table', { name: '待确认剩余作业安排' })).toContainText('2026-10-15')
  await page.getByLabel('连续性确认来源', { exact: true }).fill('现场连续执行点检')
  await page.getByRole('button', { name: '关闭对象面板', exact: true }).click()
  await page.getByRole('button', { name: '打开对象面板', exact: true }).click()
  await expect(page.getByLabel('连续性确认来源', { exact: true })).toHaveValue('现场连续执行点检')
  const before = await head()
  await page.getByRole('button', { name: '确认剩余切机可连续执行', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(detail).toContainText('确认有效')
  expect((await head()).revision).toBe(before.revision)
  await page.getByRole('button', { name: '查看预览', exact: true }).click()
  await expect(page.getByRole('region', { name: '连续性确认影响', exact: true })).toContainText('现场连续执行点检')
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '正式采用', exact: true }).click()
  await page.getByRole('dialog', { name: '确认正式采用', exact: true }).getByRole('button', { name: '正式采用', exact: true }).click()
  await expect(page.getByText(/已正式采用第 1 版/)).toBeVisible()
  const adopted = await head()
  expect(adopted.latest_adoption).toBe(1)
  expect(adopted.evaluation.executable).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await page.getByRole('button', { name: '安排剩余作业 continuity-r-s', exact: true }).click()
  await expect(detail).toContainText('确认有效')
  await expect(detail).toContainText('现场连续执行点检')
  await expect(detail).toContainText('SHARED_EDITOR')
  const original = await (await page.request.get('/planning/api/plans/adoptions/1')).json()
  await page.getByLabel('剩余切机顺序 1', { exact: true }).fill('2')
  await page.getByRole('button', { name: '加入剩余切机并预览', exact: true }).click()
  await expect(detail).toContainText('原确认已失效')
  await expect(detail).toContainText('剩余切机安排')
  await page.getByRole('button', { name: '重新核对连续性并预览', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '重新核对连续性必须填写原因' })).toBeVisible()
  await page.getByLabel('连续性重新核对原因', { exact: true }).fill('重新核对改排顺序，保留先后冲突待处理')
  await page.getByRole('button', { name: '重新核对连续性并预览', exact: true }).click()
  await expect(detail).toContainText('确认有效')
  await page.getByRole('button', { name: '查看预览', exact: true }).click()
  await expect(page.getByRole('table', { name: '完整业务问题', exact: true })).toContainText('切机尚未完成')
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeDisabled()
  await page.getByRole('tabpanel', { name: '变更预览' }).getByText('保存为待处理草稿', { exact: true }).click()
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const current = await head()
  const calendar = await page.request.post('/planning/api/inputs/apply', { headers, data: {
    base_version: current.input_version, changes: { holidays: [{ date: '2026-10-15', holiday: true }] },
  } })
  expect(calendar.ok(), await calendar.text()).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await page.getByRole('button', { name: '安排剩余作业 continuity-r-s', exact: true }).click()
  await expect(detail).toContainText('原确认已失效')
  await expect(detail).toContainText('日历与可用工时')
  await page.getByLabel('连续性重新核对原因', { exact: true }).fill('日历变化后重新核对，容量与先后冲突继续处理')
  await page.getByRole('button', { name: '重新核对连续性并预览', exact: true }).click()
  await expect(detail).toContainText('确认有效')
  await page.getByRole('button', { name: '查看预览', exact: true }).click()
  await expect(page.getByRole('button', { name: '正式采用', exact: true })).toBeDisabled()
  await expect(page.getByRole('table', { name: '完整业务问题', exact: true })).toContainText('可用')
  await page.getByRole('tabpanel', { name: '变更预览' }).getByText('保存为待处理草稿', { exact: true }).click()
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const pending = await head()
  expect(pending.latest_adoption).toBe(1)
  expect(pending.evaluation.executable).toBe(false)
  expect(pending.workspace_view.switch_continuity[0].status).toBe('valid')
  expect(pending.context.switch_continuity.audit).toHaveLength(3)
  expect(await (await page.request.get('/planning/api/plans/adoptions/1')).json()).toEqual(original)
  await save([{ kind: 'confirm_line_states', rows: [{ line_code: 'L', effective_at: '2026-10-14T08:00:00+08:00', state: 'unfinished_switch', recipe_code: null,
    source: '周三后续进度', unfinished_switch: { job_id: 'continuity-r-s', started_at: '2026-10-11T20:00:00+08:00', from_recipe: 'R', to_recipe: 'S', remaining_hours: '2' } }] }])
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_VIEWER')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name: '线体状态', exact: true }).click()
  await page.getByRole('button', { name: '查看剩余作业 continuity-r-s', exact: true }).click()
  await expect(detail).toContainText('原确认已失效')
  await expect(detail).toContainText('现场进度依据')
  await expect(detail).toContainText('现场连续执行点检')
  await expect(detail).toContainText('SHARED_EDITOR')
  await expect(page.getByLabel('连续性确认来源', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '重新核对连续性并预览', exact: true })).toHaveCount(0)
})
