import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('editor maintains inputs through preview, paste and standard Excel download', async ({ page }) => {
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('admin')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '系统管理', exact: true }).click()
  await page.getByRole('textbox', { name: '授权账号' }).fill('EDITOR')
  await page.getByRole('group', { name: '角色' }).getByText('业务编辑者', { exact: true }).click()
  await page.getByRole('button', { name: '保存授权' }).click()
  await expect(page.getByText('已保存 EDITOR 的授权', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('editor')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '需求与资料', exact: true }).click()
  await page.getByRole('link', { name: '基础资料', exact: true }).click()
  await expect(page.getByRole('heading', { name: '基础资料', exact: true })).toBeVisible()
  await page.getByLabel('资料类别', { exact: true }).selectOption('recipes')
  await page.getByRole('button', { name: '新增一行' }).click()
  await page.getByLabel('编码 第1行', { exact: true }).fill('UI_R')
  await page.getByLabel('名称 第1行', { exact: true }).fill('测试工艺')
  await page.getByRole('button', { name: '预览表格变更' }).click()
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await expect(page.getByLabel('编码 第1行', { exact: true })).toBeDisabled()
  const applied=await(await page.request.get('/planning/api/inputs')).json()
  expect(applied.masters.recipes).toContainEqual({code:'UI_R',name:'测试工艺',active:true})
  await page.getByLabel('资料类别', { exact: true }).selectOption('models')
  await page.getByRole('button', { name: '新增一行' }).click()
  await page.getByLabel('编码 第1行', { exact: true }).fill('UI_M')
  await page.getByLabel('名称 第1行', { exact: true }).fill('测试机种')
  await page.getByLabel('Recipe 编码 第1行', { exact: true }).selectOption('UI_R')
  await page.getByRole('button', { name: '新增一行' }).click()
  await page.getByLabel('编码 第2行', { exact: true }).fill('UI_N')
  await page.getByLabel('名称 第2行', { exact: true }).fill('测试机种二')
  await page.getByLabel('Recipe 编码 第2行', { exact: true }).selectOption('UI_R')
  await page.getByRole('button', { name: '预览表格变更' }).click()
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()

  await page.getByLabel('资料类别', { exact: true }).selectOption('line_yields')
  await expect(page.getByRole('heading', { name: '线体良率', exact: true })).toBeVisible()
  await page.getByLabel('粘贴表格', { exact: true }).fill('month\tpercent\n2026-10\t95\n2026-10\t80')
  const legacyPreview = page.waitForResponse(response => response.url().endsWith('/inputs/paste/preview'))
  await page.getByRole('button', { name: '预览粘贴内容' }).click()
  expect((await legacyPreview).ok()).toBe(true)
  await expect(page.getByRole('table', { name: '导入错误' })).toContainText('旧格式缺少机种列 model_code，请使用包含机种的新格式或新模板')
  await expect(page.getByRole('button', { name: '确认提交整批' })).toBeDisabled()
  const afterLegacy = await(await page.request.get('/planning/api/inputs')).json()
  expect(afterLegacy.parameters.line_yields.filter((row: Record<string, string>) => row.month === '2026-10')).toEqual([])

  await page.getByLabel('粘贴表格', { exact: true }).fill('month\tmodel_code\tpercent\n2026-10\tUI_M\t95\n2026-10\tUI_N\t80')
  const currentPreview = page.waitForResponse(response => response.url().endsWith('/inputs/paste/preview'))
  await page.getByRole('button', { name: '预览粘贴内容' }).click()
  expect((await currentPreview).ok()).toBe(true)
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  const yieldApply = page.waitForResponse(response => response.url().endsWith('/inputs/apply'))
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  const savedInputs = await(await yieldApply).json()
  expect(savedInputs.parameters.line_yields
    .filter((row: Record<string, string>) => row.month === '2026-10')
    .map((row: Record<string, string>) => [row.model_code, row.percent]))
    .toEqual([['UI_M', '95'], ['UI_N', '80']])
  await page.getByLabel('资料类别', { exact: true }).selectOption('recipes')
  await page.getByLabel('搜索资料', { exact: true }).fill('UI_R')
  await expect(page.getByLabel('编码 第1行', { exact: true })).toHaveValue('UI_R')
  await page.getByLabel('搜索资料', { exact: true }).clear()
  await page.getByLabel('资料类别', { exact: true }).selectOption('lines')
  await page.getByLabel('粘贴表格', { exact: true }).fill('code\tname\tactive\nUI_L\t测试线\ttrue')
  await page.getByRole('button', { name: '预览粘贴内容' }).click()
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await page.getByLabel('资料类别', { exact: true }).selectOption('maintenance')
  await page.getByLabel('粘贴表格', { exact: true }).fill('date\tline_code\thours\n2026-10-17\tUI_L\t20\n2026-10-18\tUI_L\t')
  await page.getByRole('button', { name: '预览粘贴内容' }).click()
  await expect(page.getByRole('table', { name: '导入错误' })).toContainText('3')
  await expect(page.getByRole('button', { name: '确认提交整批' })).toBeDisabled()
  const templateDownload = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载标准 Excel 模板' }).click()
  const template = await templateDownload
  expect(template.suggestedFilename()).toBe('auto-plan-input-template.xlsx')
  const templatePreview = page.waitForResponse(response => response.url().includes('/inputs/excel/preview'))
  await page.getByLabel('导入标准 Excel 并预览', { exact: true }).setInputFiles({
    name: template.suggestedFilename(), mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    buffer: readFileSync((await template.path())!),
  })
  expect((await templatePreview).ok()).toBe(true)
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认提交整批' })).toBeEnabled()

  const exportDownload = page.waitForEvent('download')
  await page.getByRole('link', { name: '导出当前资料 Excel' }).click()
  const exported = await exportDownload
  expect(exported.suggestedFilename()).toMatch(/^auto-plan-input-v\d+\.xlsx$/)
  const exportPreview = page.waitForResponse(response => response.url().includes('/inputs/excel/preview'))
  await page.getByLabel('导入标准 Excel 并预览', { exact: true }).setInputFiles({
    name: exported.suggestedFilename(), mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    buffer: readFileSync((await exported.path())!),
  })
  const exportPreviewResponse = await exportPreview
  expect(exportPreviewResponse.ok()).toBe(true)
  const exportPreviewBody = await exportPreviewResponse.json()
  expect(exportPreviewBody.valid).toBe(true)
  expect(exportPreviewBody.changes.line_yields
    .filter((row: Record<string, string>) => row.month === '2026-10')
    .map((row: Record<string, string>) => [row.model_code, row.percent]))
    .toEqual([['UI_M', '95'], ['UI_N', '80']])
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await page.screenshot({ path: '/tmp/auto-plan-spec-42-45-inputs.png', fullPage: true })
  await page.context().setOffline(true)
  await expect(page.getByRole('button', { name: '新增一行' })).toBeDisabled()
})
