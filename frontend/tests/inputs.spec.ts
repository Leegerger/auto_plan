import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('editor maintains inputs through preview, paste and standard Excel download', async ({ page }) => {
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('admin')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '系统管理', exact: true }).click()
  await page.getByRole('textbox', { name: '授权账号' }).fill('EDITOR')
  await page.getByRole('group', { name: '角色' }).getByText('业务编辑者', { exact: true }).click()
  await page.getByRole('button', { name: '保存授权' }).click()
  await expect(page.getByText('已保存 EDITOR 的授权', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('editor')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '需求与资料', exact: true }).click()
  await page.getByRole('link', { name: '基础资料', exact: true }).click()
  await expect(page.getByRole('heading', { name: '基础资料', exact: true })).toBeVisible()
  await page.getByLabel('资料类别', { exact: true }).selectOption('recipes')
  await page.getByRole('button', { name: '新增一行' }).click()
  await page.getByLabel('编码 第1行', { exact: true }).fill('UI_R')
  await page.getByLabel('名称 第1行', { exact: true }).fill('测试工艺')
  await page.getByRole('button', { name: '预览表格变更' }).click()
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await expect(page.getByLabel('编码 第1行', { exact: true })).toBeDisabled()
  const applied=await(await page.request.get('/planning/api/inputs')).json()
  expect(applied.masters.recipes).toContainEqual({code:'UI_R',name:'测试工艺',active:true})
  await page.getByLabel('搜索资料', { exact: true }).fill('UI_R')
  await expect(page.getByLabel('编码 第1行', { exact: true })).toHaveValue('UI_R')
  await page.getByLabel('搜索资料', { exact: true }).clear()
  await page.getByLabel('资料类别', { exact: true }).selectOption('lines')
  await page.getByLabel('粘贴表格', { exact: true }).fill('code\tname\tactive\nUI_L\t测试线\ttrue')
  await page.getByRole('button', { name: '预览粘贴内容' }).click()
  await page.getByRole('button', { name: '确认提交整批' }).click()
  await expect(page.getByText(/已提交资料版本/)).toBeVisible()
  await page.getByLabel('资料类别', { exact: true }).selectOption('maintenance')
  await page.getByLabel('粘贴表格', { exact: true }).fill('date\tline_code\thours\n2026-10-17\tUI_L\t20\n2026-10-18\tUI_L\t')
  await page.getByRole('button', { name: '预览粘贴内容' }).click()
  await expect(page.getByRole('table', { name: '导入错误' })).toContainText('3')
  await expect(page.getByRole('button', { name: '确认提交整批' })).toBeDisabled()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '下载标准 Excel 模板' }).click()
  const template = await download
  expect(template.suggestedFilename()).toBe('auto-plan-input-template.xlsx')
  await page.getByLabel('导入标准 Excel 并预览', { exact: true }).setInputFiles({
    name: template.suggestedFilename(), mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    buffer: readFileSync((await template.path())!),
  })
  await expect(page.getByText('预览通过，尚未提交', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认提交整批' })).toBeEnabled()
  await page.screenshot({ path: '/tmp/auto-plan-spec-23/inputs-ui.png', fullPage: true })
  await page.context().setOffline(true)
  await expect(page.getByRole('button', { name: '新增一行' })).toBeDisabled()
})
