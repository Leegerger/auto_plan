import { test, expect } from '@playwright/test'
const headers={Origin:`https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT ?? '8774'}`,'X-Auto-Plan-Request':'1'}

test('selected history stays frozen and restoration persists only a server reference',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires frozen shared plan')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'共享计划',exact:true}).click()
  const current=await(await page.request.get('/planning/api/plans/current')).json()
  const historical=await(await page.request.get(`/planning/api/plans/revisions/${current.revision}`)).json()
  const response=await page.request.post('/planning/api/plans/save',{headers,data:{base_revision:current.revision,input_version:current.input_version,latest_adoption:current.latest_adoption,operation_id:crypto.randomUUID(),pending:true,operations:[{kind:'patch_plan',segments:[{...current.plan.segments[0],quantity:current.plan.segments[0].quantity+1}]}]}})
  expect(response.ok()).toBeTruthy()
  await page.reload()
  const panel=page.getByRole('region',{name:'历史版本'})
  await expect(panel).toBeVisible()
  await page.getByLabel('选择历史版本',{exact:true}).selectOption(`revision:${current.revision}`)
  await expect(page.getByRole('table',{name:'历史每日投入'})).toContainText(String(historical.plan.segments[0].quantity))
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出选定快照 Excel',exact:true}).click()
  expect((await download).suggestedFilename()).toBe(`auto-plan-revision-${current.revision}.xlsx`)
  await page.getByRole('button',{name:'恢复为新草稿并预览',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  const beforeSave=await(await page.request.get('/planning/api/plans/current')).json()
  expect(beforeSave.revision).toBe(current.revision+1)
  const local=await page.evaluate(()=>Object.entries(localStorage).filter(([key])=>key.includes(':draft:')).map(([,raw])=>JSON.parse(raw)).find(row=>row.draft?.operations.some((op:{kind:string})=>op.kind==='restore_history')))
  expect(local.draft.operations[0].source).toEqual({kind:'revision',id:current.revision})
  expect(local.draft.operations[0]).not.toHaveProperty('plan')
  expect(local).not.toHaveProperty('evaluation')
  await page.reload()
  await page.getByRole('button',{name:'恢复本机临时稿',exact:true}).click()
  await page.getByRole('button',{name:'预览本机修改',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(`已共享保存修订 ${current.revision+2}，最近采用版未改变`,{exact:true})).toBeVisible()
  expect((await(await page.request.get(`/planning/api/plans/revisions/${current.revision}`)).json()).snapshot).toEqual(historical.snapshot)
})

test('viewer can inspect and download history without restoration controls',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires frozen shared plan')
  await page.request.post('/planning/api/auth/login',{headers,data:{username:'ADMIN',password:'company-secret'}})
  expect((await page.request.put('/planning/api/admin/authorizations/HISTORY_VIEWER',{headers,data:{roles:['viewer']}})).ok()).toBeTruthy()
  await page.request.post('/planning/api/auth/login',{headers,data:{username:'HISTORY_VIEWER',password:'company-secret'}})
  await page.goto('/planning/plans/shared')
  await expect(page.getByRole('table',{name:'历史每日投入'})).toBeVisible()
  await expect(page.getByRole('button',{name:'恢复为新草稿并预览',exact:true})).toHaveCount(0)
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出选定快照 Excel',exact:true}).click()
  expect((await download).suggestedFilename()).toContain('auto-plan-revision-')
})
