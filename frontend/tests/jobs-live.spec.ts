import { test, expect } from '@playwright/test'

test('durable job computes in a fresh worker and applies a server reference through the shared owner',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_TRANSACTIONS_FIXTURE!=='1','Requires frozen shared-plan persistence adapter')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  const source=await(await page.request.get('/planning/api/plans/current')).json()
  await page.getByRole('link',{name:'共享计划',exact:true}).click()
  await page.getByLabel('计算范围起日',{exact:true}).fill('2026-10-15')
  await page.getByLabel('计算范围终日',{exact:true}).fill('2026-10-15')
  await page.getByLabel('计算线体',{exact:true}).selectOption(['L'])
  await page.getByLabel('计算时限',{exact:true}).fill('1')
  await page.getByRole('button',{name:'提交计算任务',exact:true}).click()
  const jobs=page.getByRole('region',{name:'计算任务'})
  await expect(jobs).toContainText('计算任务已接收')
  await expect(jobs).toContainText('执行状态 已完成',{timeout:15000})
  const listed=await(await page.request.get('/planning/api/jobs')).json()
  expect(listed.jobs).toHaveLength(1)
  expect(listed.jobs[0].source_revision).toBe(source.revision)
  await page.getByRole('button',{name:'查看候选内容',exact:true}).click()
  await expect(page.getByRole('region',{name:'候选内容'})).toContainText('需要重新检查')
  await page.getByRole('button',{name:'预览完整候选',exact:true}).click()
  await expect(page.getByText('预览完成，尚未共享',{exact:true})).toBeVisible()
  const stored=await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.includes('draft')).map(key=>localStorage.getItem(key)).join('\n'))
  expect(stored).toContain('apply_candidate')
  await page.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved=await(await page.request.get('/planning/api/plans/current')).json()
  expect(saved.revision).toBe(source.revision+1)
  expect(saved.latest_adoption).toBe(source.latest_adoption)
  expect(saved.plan.segments).toEqual([])
})
