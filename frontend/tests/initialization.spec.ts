import { test, expect } from '@playwright/test'
test('import full standard workbook as pending then replace demand date with independent duplicate rows',async({page})=>{
 test.skip(process.env.AUTO_PLAN_BROWSER_INITIALIZATION_FIXTURE!=='1','Requires explicit initialization fixture')
 await page.goto('/planning/login')
 await page.getByRole('textbox',{name:'公司账号'}).fill('IMPORT_EDITOR')
 await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.getByRole('link',{name:'首次接入与需求',exact:true}).click()
 await page.locator('input[type=file]').setInputFiles('/tmp/auto-plan-spec-23/initialization-fixture.xlsx')
 await expect(page.getByRole('status')).toHaveText('预览通过，尚未写入。')
 expect((await(await page.request.get('/planning/api/plans/current')).json()).revision).toBe(0)
 await page.route('**/api/initialization/apply',async route=>{await route.fetch();await route.abort('failed')},{times:1})
 await page.getByRole('button',{name:'确认导入待处理草稿',exact:true}).click()
 await expect(page.getByText('前次导入结果待核实，当前只读。核实完成后才能继续提交。')).toBeVisible()
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('auto-plan-import-pending:/planning:IMPORT_EDITOR')!))
 expect(Object.keys(stored).sort()).toEqual(['mode','operation_id'])
 await page.reload()
 await page.getByRole('button',{name:'核实前次导入',exact:true}).click()
 await expect(page.getByText('前次导入已提交，已重新读取。')).toBeVisible()
 const current=await(await page.request.get('/planning/api/plans/current')).json()
 expect([current.revision,current.latest_adoption,current.pending,current.plan.segments[0].quantity]).toEqual([1,0,true,1400])
 await page.getByText('按日需求变更',{exact:true}).click()
 await page.locator('textarea').fill('model_code\tweek\tweek_label\tdelta\nM\t2026-10-12\tW202642\t200\nM\t2026-10-12\tW202642\t200')
 await page.getByRole('button',{name:'读取粘贴并预览',exact:true}).click()
 await expect(page.getByRole('status')).toHaveText('预览通过，尚未写入。')
 await page.getByRole('button',{name:'确认替换整日需求文件',exact:true}).click()
 await expect(page.getByText('整日需求文件已替换，旧版本保留。')).toBeVisible()
 const inputs=await(await page.request.get('/planning/api/inputs?version=2')).json()
 expect(inputs.business.demands).toEqual([{model_code:'M',week:'2026-10-12',quantity:400}])
 expect((await(await page.request.get('/planning/api/plans/current')).json()).revision).toBe(1)
 await page.getByText('需求文件版本和独立行',{exact:true}).click()
 await expect(page.getByText('2026-10-14 第1版 已被替换')).toBeVisible()
 await expect(page.getByText('2026-10-14 第2版 当前有效')).toBeVisible()
 // A storage failure must still allow an explicit server import and in-page verification.
 await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new DOMException('quota','QuotaExceededError')};Storage.prototype.removeItem=()=>{throw new DOMException('denied','SecurityError')}})
 await page.getByRole('button',{name:'读取粘贴并预览',exact:true}).click()
 await page.route('**/api/demands/apply',async route=>{await route.fetch();await route.abort('failed')},{times:1})
 await page.getByRole('button',{name:'确认替换整日需求文件',exact:true}).click()
 await expect(page.getByText(/浏览器无法保存核实编号/)).toBeVisible()
 await page.getByRole('button',{name:'核实前次导入',exact:true}).click()
 await expect(page.getByText('前次导入已提交，已重新读取。')).toBeVisible()
 expect((await(await page.request.get('/planning/api/plans/current')).json()).input_version).toBe(3)
 await page.screenshot({path:'/tmp/auto-plan-spec-23/initialization-ui.png',fullPage:true})
})
