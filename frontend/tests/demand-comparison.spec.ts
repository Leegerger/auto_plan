import { test, expect, type Page } from '@playwright/test'

async function enter(page:Page){
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_EDITOR')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
}

test('independent line comparison keeps the target through selection and source changes', async ({ page }) => {
  test.skip(process.env.AUTO_PLAN_BROWSER_DEMAND_COMPARISON_FIXTURE !== '1', 'Requires explicit comparison fixture')
  await enter(page)
  await page.getByRole('button', { name: '展开待处理需求', exact: true }).click()
  await page.getByRole('button', { name: '选择需求 M 2026-10-12', exact: true }).click()
  await page.getByRole('button', { name: '按需补排', exact: true }).click()
  const before = await (await page.request.get('/planning/api/plans/current')).json()
  await page.getByLabel('补排投入起日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排投入终日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排调整范围起日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排调整范围终日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('补排调整范围线体', { exact: true }).selectOption(['L','B','C','D','E','F'])
  await expect(page.getByRole('button', { name: '比较授权线体', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '比较授权线体', exact: true }).click()
  const comparison = page.getByRole('region', { name: '独立线体补排比较', exact: true })
  await expect(comparison).toBeVisible()
  const table = comparison.getByRole('table', { name: '独立线体比较结果', exact: true })
  const line = (code:string,name:string) => table.locator('tbody tr').filter({hasText:`${code} ${name}`})
  await expect(table.locator('tbody tr')).toHaveCount(6)
  await expect(comparison).toContainText('各行的覆盖量和容量不能相加')
  await expect(line('L','一线')).toContainText('600 片投入')
  await expect(line('B','高产能线')).toContainText('1000 片投入')
  await expect(line('C','已占满线')).toContainText('剩余容量')
  await expect(line('D','零产能线')).toContainText('全日产能明确为零')
  await expect(line('E','缺产能线')).toContainText('待完成计算 片投入')
  await expect(line('F','禁排线')).toContainText('明确禁止生产 Recipe R')
  await page.getByRole('button', { name: '查看 B 完整安排', exact: true }).click()
  const detail = page.getByRole('region', { name: 'B 线体完整安排', exact: true })
  await expect(detail.getByRole('table', { name: '建议逐日投入', exact: true })).toContainText('1000')
  expect(await (await page.request.get('/planning/api/plans/current')).json()).toEqual(before)

  await page.getByLabel('补排合格产出目标', { exact: true }).fill('700')
  await expect(comparison).toHaveCount(0)
  await expect(page.getByText('线体比较已失效，覆盖目标和日期已保留，请重新比较。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '比较授权线体', exact: true }).click()
  await expect(line('B','高产能线')).toContainText('700 片投入')
  const inputs = await (await page.request.get('/planning/api/inputs')).json()
  const maintained = await page.request.post('/planning/api/inputs/apply', { headers: {
    Origin:`https://localhost:${process.env.AUTO_PLAN_BROWSER_PORT ?? '8806'}`, 'X-Auto-Plan-Request':'1',
  }, data:{base_version:inputs.input_version,changes:{maintenance:[{date:'2026-10-15',line_code:'B',hours:12}]}} })
  expect(maintained.ok(),await maintained.text()).toBe(true)
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '需求与资料', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await expect(comparison).toHaveCount(0)
  await expect(page.getByLabel('补排合格产出目标', { exact: true })).toHaveValue('700')
  await expect(page.getByLabel('补排投入起日', { exact: true })).toHaveValue('2026-10-15')
  await expect(page.getByLabel('补排投入终日', { exact: true })).toHaveValue('2026-10-15')
  await page.getByRole('button', { name: '比较授权线体', exact: true }).click()
  await expect(line('B','高产能线')).toContainText('500 片投入')

  await page.getByRole('button', { name: '2026-10-15 L 日内详情', exact: true }).click()
  await page.getByLabel('追加机种', { exact: true }).selectOption('N')
  await page.getByLabel('操作数量', { exact: true }).fill('10')
  await page.getByLabel('追加线体', { exact: true }).selectOption('L')
  await page.getByLabel('追加起日', { exact: true }).fill('2026-10-15')
  await page.getByLabel('追加终日', { exact: true }).fill('2026-10-15')
  await page.getByRole('button', { name: '加入完整动作并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(comparison).toHaveCount(0)
  await expect(page.getByLabel('补排合格产出目标', { exact: true })).toHaveValue('700')
  await page.getByRole('button', { name: '比较授权线体', exact: true }).click()
  await expect(line('B','高产能线')).toContainText('500 片投入')
  await page.getByRole('button', { name: '查看 B 完整安排', exact: true }).click()
  await expect(detail.getByRole('table', { name: '建议逐日投入', exact: true }).locator('tbody tr')).toHaveCount(1)
  await expect(detail).toContainText('剩余补排目标 200 片合格产出')
  await detail.getByRole('button', { name: '选用完整安排并预览', exact: true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact: true })).toBeVisible()
  await expect(comparison).toHaveCount(0)
  expect((await (await page.request.get('/planning/api/plans/current')).json()).revision).toBe(before.revision)
  await page.getByRole('button', { name: '共享保存', exact: true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const saved = await (await page.request.get('/planning/api/plans/current')).json()
  expect(saved.plan.segments.filter((row:{model_code:string})=>row.model_code==='M')).toEqual([
    expect.objectContaining({date:'2026-10-15',line_code:'B',quantity:500}),
  ])
  expect(saved.plan.segments.find((row:{id:string})=>row.id==='comparison-full')).toEqual(before.plan.segments[0])
  expect(saved.plan.segments.find((row:{model_code:string;line_code:string})=>row.model_code==='N' && row.line_code==='L').quantity).toBe(10)
  expect(Object.values(saved.lineage.demand_goals)).toEqual([expect.objectContaining({requested_output:700,remaining_output_target:200})])
  expect(saved.latest_adoption).toBe(0)
  await page.reload()
  await page.getByRole('button', { name: '补排目标 1', exact: true }).click()
  await expect(page.getByRole('region', { name: '补排目标余额', exact: true })).toContainText('200 片合格产出')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('SHARED_VIEWER')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await expect(page.getByRole('button', { name: '比较授权线体', exact: true })).toHaveCount(0)
})

for(const viewport of [{width:1280,height:800},{width:1440,height:900}]){
  test(`representative comparison retains demand and date context at ${viewport.width}px`,async({page})=>{
    test.skip(process.env.AUTO_PLAN_BROWSER_WORKSPACE_FIXTURE!=='1','Requires representative18line40model15week source')
    await page.setViewportSize(viewport)
    await enter(page)
    await expect(page.getByLabel('筛选机种').locator('option')).toHaveCount(41)
    await expect(page.getByRole('table',{name:'十五周日期线体计划'}).locator('tbody tr')).toHaveCount(18)
    const entry=await page.getByRole('region',{name:'周矩阵滚动区域'}).boundingBox()
    expect(entry!.y).toBeLessThan(viewport.height-40)
    await page.getByRole('button',{name:'展开待处理需求',exact:true}).click()
    await page.getByRole('button',{name:'选择需求 M 2027-01-18',exact:true}).click()
    await page.getByRole('button',{name:'按需补排',exact:true}).click()
    await page.getByLabel('补排投入起日',{exact:true}).fill('2027-01-21')
    await page.getByLabel('补排投入终日',{exact:true}).fill('2027-01-21')
    await page.getByLabel('补排调整范围起日',{exact:true}).fill('2027-01-21')
    await page.getByLabel('补排调整范围终日',{exact:true}).fill('2027-01-21')
    await page.getByLabel('补排调整范围线体',{exact:true}).selectOption(['L',...Array.from({length:17},(_,n)=>`L${String(n+2).padStart(2,'0')}`)])
    const response=page.waitForResponse(response=>response.url().endsWith('/plans/demand-comparison') && response.request().method()==='POST')
    const started=Date.now()
    await page.getByRole('button',{name:'比较授权线体',exact:true}).click()
    const answer=await response
    console.log(`comparison ${viewport.width}px18line request ${Date.now()-started}ms, ${(await answer.body()).length}bytes`)
    expect(answer.ok(),await answer.text()).toBe(true)
    const comparison=page.getByRole('region',{name:'独立线体补排比较',exact:true})
    await expect(comparison.getByRole('table',{name:'独立线体比较结果'}).locator('tbody tr')).toHaveCount(18)
    await expect(comparison).toContainText('覆盖目标 100 片合格产出')
    await expect(comparison).toContainText('2027-01-21 至 2027-01-21')
    await page.getByRole('button',{name:'查看 L02 完整安排',exact:true}).click()
    const detail=page.getByRole('region',{name:'L02 线体完整安排',exact:true})
    await expect(detail.getByRole('table',{name:'建议逐日投入'})).toContainText('1000')
    await page.getByRole('button',{name:'收起按需补排',exact:true}).click()
    await page.getByRole('button',{name:'按需补排',exact:true}).click()
    await expect(page.getByLabel('补排合格产出目标',{exact:true})).toHaveValue('100')
    await expect(page.getByLabel('补排投入起日',{exact:true})).toHaveValue('2027-01-21')
    await expect(detail).toBeVisible()
  })
}
