import { test, expect } from '@playwright/test'

test('login, nested prefix assets, authorize, last administrator, and logout', async ({ page, context }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.goto('/planning/admin')
  await expect(page.getByRole('heading', { name: '登录排程应用' })).toBeVisible()
  await page.getByRole('textbox', { name: '公司账号' }).fill(' admin ')
  await page.getByLabel('公司密码', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByText('账号或密码错误', { exact: true })).toBeVisible()
  await expect(page.getByLabel('公司密码', { exact: true })).toHaveValue('')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '欢迎，ADMIN' })).toBeVisible()
  const cookie = (await context.cookies()).find(cookie => cookie.name === 'auto_plan_session')!
  expect(cookie).toMatchObject({ httpOnly: true, secure: true, sameSite: 'Strict', path: '/planning' })
  await page.getByRole('link', { name: '账号授权', exact: true }).click()
  await expect(page.getByRole('heading', { name: '账号授权', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: '授权账号' }).fill('reviewer')
  await page.getByRole('group', { name: '角色' }).getByText('查看者', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '查看者' })).toBeChecked()
  await page.getByRole('button', { name: '保存授权' }).click()
  await expect(page.getByText('已保存 REVIEWER 的授权', { exact: true })).toBeVisible()
  await page.getByRole('row').filter({ hasText: 'ADMIN' }).getByRole('button', { name: '编辑' }).click()
  await page.getByRole('group', { name: '角色' }).getByText('管理员', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '管理员' })).not.toBeChecked()
  await page.getByRole('button', { name: '保存授权' }).click()
  await expect(page.getByText('至少保留一个有效管理员', { exact: true })).toBeVisible()
  await context.setOffline(true)
  await expect(page.getByText('网络已断开，恢复连接后才能继续操作', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '保存授权' })).toBeDisabled()
  await context.setOffline(false)
  await page.reload()
  await expect(page.getByRole('heading', { name: '账号授权', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '登录排程应用' })).toBeVisible()
  expect(failures).toEqual([])
})
