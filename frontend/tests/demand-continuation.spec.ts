  expect(trial.ok(), await trial.text()).toBe(true)
  const first = (await trial.json()).operation
  const saved = await page.request.post('/planning/api/plans/save', { headers, data: { ...source, operations:[first], operation_id:crypto.randomUUID(), pending:true } })
  expect(saved.ok(), await saved.text()).toBe(true)
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('button', { name:'补排目标 1', exact:true }).click()
