  await goals.getByRole('button', { name:'继续补排 M 2026-11-02', exact:true }).click()
  await expect(page.getByLabel('补排合格产出目标', { exact:true })).toHaveValue('400')
  await page.getByLabel('补排投入起日', { exact:true }).fill('2026-11-03')
  await page.getByLabel('补排投入终日', { exact:true }).fill('2026-11-03')
  await page.getByLabel('补排线体', { exact:true }).selectOption('B')
  await page.getByRole('button', { name:'试算按时覆盖', exact:true }).click()
  await expect(page.getByRole('alert')).toContainText('补排投入日期须位于明确授权的窗口范围')
  await expect(page.getByLabel('补排调整范围终日', { exact:true })).toHaveValue('2026-10-18')
  await page.getByLabel('补排调整范围起日', { exact:true }).fill('2026-10-30')
  await page.getByLabel('补排调整范围终日', { exact:true }).fill('2026-11-04')
  await page.getByRole('button', { name:'试算按时覆盖', exact:true }).click()
  const result = page.getByRole('region', { name:'单线补排试算结果', exact:true })
  await expect(result).toContainText('建议投入 499 片投入')
  await expect(result).toContainText('原补排目标余额 0 片合格产出')
  await expect(result.getByRole('table', { name:'补排所需确认', exact:true })).toContainText('600')
  await page.getByLabel('补排合格产出目标', { exact:true }).fill('200')
  await expect(result).toHaveCount(0)
  await page.getByRole('button', { name:'试算按时覆盖', exact:true }).click()
  await expect(result).toContainText('本次覆盖目标已安排')
  await expect(result).toContainText('建议投入 249 片投入')
  await expect(result).toContainText('本次试算剩余目标 0 片合格产出')
  await expect(result).toContainText('原补排目标余额 200 片合格产出')
  await page.getByRole('button', { name:'选用完整安排并预览', exact:true }).click()
  await expect(goals).toContainText('剩余补排目标 200 片合格产出')
  await page.reload()
  await page.getByRole('button', { name:/本机临时稿/ }).click()
  await expect(page.getByRole('button', { name:'恢复本机临时稿', exact:true })).toBeVisible()
  await page.getByRole('button', { name:'恢复本机临时稿', exact:true }).click()
  await page.getByRole('button', { name:'预览本机修改', exact:true }).click()
  await expect(page.getByText('预览完成，尚未共享', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:'继续编辑', exact:true }).click()
