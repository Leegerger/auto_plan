import { test, expect, type Page } from '@playwright/test'

async function savePending(page:Page, highRisk=false){
  await page.getByRole('button', { name:/本机临时稿/ }).click()
  const actions=page.getByRole('tabpanel', { name:'本机动作', exact:true })
  if(!await actions.getByRole('checkbox', { name:'保存为待处理草稿', exact:true }).isChecked())await actions.getByText('保存为待处理草稿', { exact:true }).click()
  await expect(actions.getByRole('checkbox', { name:'保存为待处理草稿', exact:true })).toBeChecked()
  await page.getByRole('button', { name:'继续编辑', exact:true }).click()
  await page.getByRole('button', { name:'共享保存', exact:true }).click()
  if(highRisk)await page.getByRole('dialog', { name:'确认高风险变更', exact:true }).getByRole('button', { name:'共享保存', exact:true }).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
}

