import { randomUUID } from 'node:crypto'
import { test, expect, type Page } from '@playwright/test'

async function openReset(page:Page){
  await page.getByRole('navigation',{name:'分区导航'}).getByRole('link',{name:'执行与重置',exact:true}).click()
  await expect(page.getByRole('region',{name:'执行事实与每周重置'})).toBeVisible()
}
async function openPreview(page:Page){
  await page.getByRole('button',{name:'查看预览',exact:true}).click()
  return page.getByRole('dialog',{name:'变更预览'})
}
async function adopt(page:Page){
  const preview=await openPreview(page)
  await preview.getByRole('button',{name:'正式采用',exact:true}).click()
  await page.getByRole('dialog',{name:'确认正式采用'}).getByRole('button',{name:'正式采用',exact:true}).click()
}

test('Chinese facts and reset editor keeps source, complete pairing and correction choices in the shared queue',async({page})=>{
  test.skip(process.env.AUTO_PLAN_BROWSER_RESET_FIXTURE!=='1','Requires frozen reset fixture')
  await page.goto('/planning/login')
  await page.getByRole('textbox',{name:'公司账号'}).fill('RESET_EDITOR')
  await page.getByLabel('公司密码',{exact:true}).fill('company-secret')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'排程',exact:true}).click()
  await openReset(page)
  const panel=page.getByRole('region',{name:'执行事实与每周重置'})
  const inputs=await(await page.request.get('/planning/api/inputs')).json()
  const retired=await page.request.post('/planning/api/inputs/apply',{headers:{Origin:new URL(page.url()).origin,'X-Auto-Plan-Request':'1'},data:{base_version:inputs.input_version,changes:{models:[{code:'RETIRED',name:'已停用且无来源事实',recipe_code:'R',active:false}]}}})
  expect(retired.status()).toBe(200)
  await page.reload()
  await expect(panel).toBeVisible()
  await expect(page.getByLabel('RETIRED 周一起始在制品',{exact:true})).toHaveCount(0)
  await page.getByLabel('重置批次',{exact:true}).fill('browser-monday')
  for(const model of ['M','N','P']){
    await page.getByLabel(`${model} 周一起始在制品`,{exact:true}).fill('0')
    await page.getByLabel(`${model} 最终净余额`,{exact:true}).fill(model==='M'?'600':'0')
  }
  await page.getByRole('button',{name:'预览本周重置',exact:true}).click()
  await expect(page).toHaveURL(/\/planning\/schedule$/)
  const first=await openPreview(page)
  await expect(first.getByRole('table',{name:'重置周目标与未完成调整'})).toContainText('1400')
  await expect(first).toContainText('计算来源采用版 1')
  await expect(first).toContainText('稳定性比较采用版 1')
  await first.getByRole('button',{name:'正式采用',exact:true}).click()
  await page.getByRole('dialog',{name:'确认正式采用'}).getByRole('button',{name:'正式采用',exact:true}).click()
  await expect(page.getByText('已正式采用第 2 版',{exact:true})).toBeVisible()
  const adopted=await(await page.request.get('/planning/api/plans/current')).json()
  const late=adopted.plan.segments.find((row:{id:string})=>row.id==='late')
  const adjusted=await page.request.post('/planning/api/plans/adopt',{headers:{Origin:new URL(page.url()).origin,'X-Auto-Plan-Request':'1'},data:{base_revision:adopted.revision,input_version:adopted.input_version,latest_adoption:adopted.latest_adoption,operation_id:randomUUID(),operations:[{kind:'patch_plan',segments:[{...late,quantity:500,hours:'13'}]}]}})
  expect(adjusted.status()).toBe(200)
  await page.reload()
  await openReset(page)
  await page.getByLabel('更正本周重置',{exact:true}).check()
  await page.getByLabel('M 最终净余额',{exact:true}).fill('500')
  await page.getByRole('button',{name:'预览本周重置',exact:true}).click()
  await expect(page).toHaveURL(/\/planning\/schedule$/)
  const corrected=await openPreview(page)
  await expect(corrected.getByRole('table',{name:'重置周目标与未完成调整'})).toContainText('1500')
  await expect(corrected).toContainText('稳定性比较采用版 3')
  await expect(corrected.getByRole('button',{name:'正式采用',exact:true})).toBeDisabled()
  await corrected.getByRole('button',{name:'继续编辑',exact:true}).click()
  await openReset(page)
  await page.getByLabel('修订 3 的重置更正选择',{exact:true}).selectOption('keep')
  const finalCommand=page.waitForRequest(request=>request.url().endsWith('/api/plans/preview')&&request.postDataJSON()?.operations?.some((operation:{kind?:string;choices?:unknown[]})=>operation.kind==='weekly_reset'&&operation.choices?.length))
  await page.getByRole('button',{name:'按逐项选择重新预览重置',exact:true}).click()
  const resetCommand=(await finalCommand).postDataJSON()
  expect(resetCommand.operations[0].choices).toEqual([{revision:3,retain:true}])
  await expect(page).toHaveURL(/\/planning\/schedule$/)
  const finalReset=await openPreview(page)
  await expect(finalReset.getByRole('table',{name:'重置周目标与未完成调整'})).toContainText('1500')
  await finalReset.getByRole('button',{name:'正式采用',exact:true}).click()
  await page.getByRole('dialog',{name:'确认正式采用'}).getByRole('button',{name:'正式采用',exact:true}).click()
  await expect(page.getByText('已正式采用第 4 版',{exact:true})).toBeVisible()
  await openReset(page)
  await page.getByLabel('事实机种',{exact:true}).selectOption('M')
  await page.getByLabel('累计实际投入',{exact:true}).fill('20')
  await page.getByRole('button',{name:'加入累计事实',exact:true}).click()
  await page.getByRole('button',{name:'预览执行事实',exact:true}).click()
  await expect(page).toHaveURL(/\/planning\/schedule$/)
  const factsPreview=await openPreview(page)
  await factsPreview.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  const after=await(await page.request.get('/planning/api/plans/current')).json()
  expect(after.context.execution.facts[0].quantity).toBe(20)
  expect(after.context.reset.models.find((row:{model_code:string})=>row.model_code==='M').net_balance).toBe(500)
  await openReset(page)
  await page.getByLabel('累计实际投入',{exact:true}).fill('15')
  await page.getByRole('button',{name:'加入累计事实',exact:true}).click()
  await page.getByRole('button',{name:'预览执行事实',exact:true}).click()
  await expect(panel).toContainText('纠错必须填写原因')
  await page.getByLabel('事实纠错原因',{exact:true}).fill('逐笔清点更正')
  await page.getByRole('button',{name:'预览执行事实',exact:true}).click()
  await expect(page).toHaveURL(/\/planning\/schedule$/)
  const correctionPreview=await openPreview(page)
  await correctionPreview.getByRole('button',{name:'共享保存',exact:true}).click()
  await expect(page.getByText(/已共享保存修订/)).toBeVisible()
  await openReset(page)
  await page.getByText('事实纠错与登记审计',{exact:true}).click()
  await expect(page.getByRole('table',{name:'执行事实审计'})).toContainText('逐笔清点更正')
  await expect(page.getByRole('table',{name:'执行事实审计'})).toContainText('累计投入由 20 改为 15 片')
  await page.screenshot({path:'/tmp/auto-plan-spec-23/execution-reset-ui.png',fullPage:true})
})
