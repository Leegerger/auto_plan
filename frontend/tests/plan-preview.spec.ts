import { test, expect } from '@playwright/test'

test('exact-hours page is a read-only view of the current plan and points back to the schedule workspace', async ({ page }) => {
  await page.goto('/planning/login')
  await page.getByRole('textbox', { name: '公司账号' }).fill('admin')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '系统管理', exact: true }).click()
  await page.getByRole('textbox', { name: '授权账号' }).fill('PREVIEW_EDITOR')
  await page.getByRole('group', { name: '角色' }).getByText('业务编辑者', { exact: true }).click()
  await page.getByRole('button', { name: '保存授权' }).click()
  await expect(page.getByText('已保存 PREVIEW_EDITOR 的授权', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByRole('textbox', { name: '公司账号' }).fill('preview_editor')
  await page.getByLabel('公司密码', { exact: true }).fill('company-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('link', { name: '需求与资料', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '排程', exact: true }).click()
  await page.getByRole('link', { name: '日内工时', exact: true }).click()
  await expect(page.getByRole('heading', { name: '日内详情与工时预览' })).toBeVisible()
  await expect(page.getByRole('link', { name: '返回计划工作区' })).toBeVisible()
  await expect(page.getByRole('button', { name: '添加生产段' })).toHaveCount(0)
  await expect(page.getByLabel('投入片数 第1段')).toHaveCount(0)
})
